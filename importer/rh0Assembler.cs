using static DotrAssetModder.Bin;

namespace DotrAssetModder;

//Mostly AI

/* RH0 assembler.
   Combines the rebuilt sub-blocks into a single 1 MiB RH0 by TEMPLATE-INJECT: the
   original .mrg is the base, its header preamble (0x00..nodeTree) and aux2 are
   preserved VERBATIM, and only the blocks we regenerate are re-laid-out, with every
   header offset / size and TexTable pointer fixed up.

   Why template-inject rather than synthesis: the RH0 header carries a fixed preamble
   (incl. model-scale floats at +0xA8 and sectionFlags upper bits) whose exact engine
   use isn't fully reversed. RhModel_BindAddress consumes relocWalk + the four section
   bases (all regenerated correctly), and relocates each page terminator's term1
   (0x30000000|sec2Off) in place - exactly what GeometryWriter emits.

   aux0/aux1 are NOT copied: they are the per-frame lRhModel_DynamicAddressBind@0x20fed0
   fixup lists (offsets of every bone-bind d1 word + the opening-tag ADDR), tied to the
   Section1/Section1Alt layout, and are regenerated by GeometryWriter. Copying the
   originals verbatim leaves the new chain unbound -> VIF1 stall (black screen).
   aux2's consumer is unknown; it is zero-filled in retail and kept verbatim.

   Block order: header+preamble | sections 0..9 (nodeTree | section1 | section2 |
   section1Alt | section2Alt | texTable | aux0 | aux1 | relocWalk | aux2), tiling exactly as
   retail | RH2[*] | ANM[*] | MOT | post-MOT chain | pad. */

public static class Rh0Assembler
{
    /// Which regenerated section is the larger share of the 1 MiB budget when an import
    /// would overflow - passed to a confirmReduction callback so a caller (e.g. the import
    /// UI) can ask the user before trading fidelity for headroom.
    public enum OverflowCategory { Animation, Texture }

    public const uint Rh0Magic = 0x00304852;
    private const int HeaderPreambleEnd = 0xB0; // header (0x68) + fixed preamble; nodeTree starts here in stock models
    private const int AlignmentBytes = 16;
    private const int MinimumTextureWidth = 128, MinimumTextureHeight = 64; // smallest Rh2Encoder.BuildNative target

    public sealed class TextureInput
    {
        public int TextureIndex;
        public byte[]? Rgba; // edited texture (null => keep the original RH2 verbatim)
        public int Width, Height;

        /* Optional custom flipbook animation (see GlbImporter.TryParseAnimImageName /
           ImportedModel.TextureAnimFrames). When AnimationFrameCount > 1, Rgba/Width/Height
           above hold the PACKED SPRITE SHEET: frame f in cell (f % AnimationColumns,
           f / AnimationColumns) of a grid of AnimationBlockWidth x AnimationBlockHeight cells,
           frame 0 at (0, 0), which is also where the faces sample (GlbImporter.DecodeGlbTextures).
           The 7 ANM modes (flags bits 2-4), names from lSzModel_TexAnimConv's table:
             0 LOOP2, 1 LOOP, 2 REVERSE2, 3 REVERSE (ping-pong), 4 SHOT3 (window),
             5 SHOT2 (one shot), 6 SHOT (blink). All are flipbook cell copies; there is NO
             UV-scroll mode. See BuildCustomTexAnimEntry. */
        public int AnimationFrameCount;       // 0 or 1 = static texture, no ANM entry written
        public int AnimationColumns, AnimationRows;   // grid; 0 = one row of AnimationFrameCount cells
        public int AnimationBlockWidth, AnimationBlockHeight;
        public int AnimationTicksPerFrame = 5; // default matches the one real flipbook sample (aux0=aux1=5)

        /// The slot's retail texture-animation records, already packed as the 24-byte entries
        /// the game reads (GlbImporter.PackTexAnimRecords, from an extracted glb's
        /// "DOTR_texAnimRecords" material extras). The entries hold no pointers, so they are
        /// placed verbatim and only TexTable's postOff has to point at them.
        public byte[]? AnimationRecords;

        /// AnimationRecords were authored against Rgba's own Width x Height (a custom glb, e.g. a
        /// DoD export's blink records), not against a retail RH2. The slot is then encoded
        /// natively and the records' rectangles are scaled to the final texture size.
        public bool AnimRecordsInImagePixels;
    }

    /// True when a valid RH0 magic sits at <paramref name="offset"/> in <paramref name="bytes"/>.
    public static bool LooksLikeRh0(byte[] bytes, long offset)
    {
        if (offset < 0 || offset + 4 > bytes.Length) return false;
        return ReadU32(bytes, (int)offset) == Rh0Magic;
    }

    /// Throws unless <paramref name="block"/> is exactly a fixed 1 MiB RH0 block (the
    /// monster-MRG slot shape); validates a template before Assemble.
    public static void ValidateRh0Block(byte[] block, string label)
    {
        if (block.Length != GameTables.MonsterSlotSize || !LooksLikeRh0(block, 0))
            throw new Exception(label + " is not a valid 1 MiB RH0 block");
    }

    /// (category, categoryBytes, totalBytes, budget) -> true to apply that category's
    /// fidelity-reduction fallback, false to decline and let the block overflow
    /// (<see cref="Result.OverflowBytes"/>).
    /// Called at most once, only for whichever category is the larger byte share of an
    /// overflowing layout. Pass null to keep every fallback fully automatic.
    public delegate bool ConfirmReduction(OverflowCategory category, int categoryBytes, int totalBytes, int budget);

    /// See the page cap in Assemble.
    public const int MaxModelTexturePages = 31;

    /// Largest width/height (power of two) a texture is rebuilt at.
    public const int MaxTextureDim = 512;

    public sealed class Result
    {
        public byte[] Block = Array.Empty<byte>();

        /// Texture slots shed because the grown table did not fit the block, each with the slot
        /// its pages were drawn from instead (the wrong texture).
        public List<(int Slot, int Onto)> ShedTextureSlots = new();

        /// GS pages the textures take (one per RH2 section), and how many halvings the page cap made.
        public int TexturePages;
        public int HalvedForPages;

        /// How far the finished block overshot its budget, in bytes (0 = it fits), and the
        /// section/payload that first crossed the line. Assemble never throws on overflow: it
        /// returns the complete block so the caller can report "over by N B" and decide.
        public int OverflowBytes;
        public string? OverflowLabel;

        /// Battle slots the motions lacked, filled with a copy of another (MotWriter).
        public List<(int Slot, int From)> MotionClones = new();
    }

    public static Result Assemble(byte[] originalMrg, RebuildPipeline.Result rebuilt,
        IReadOnlyList<TextureInput>? textures, int blockSize, bool trimToContent,
        ConfirmReduction confirmReduction, bool ownSizeTextures)
    {
        if (ReadU32(originalMrg, 0) != Rh0Magic) throw new InvalidOperationException("template is not an RH0");
        var result = new Result();

        byte[] nodeTree = NodeTreeWriter.Write(rebuilt.Nodes,
            (rebuilt.BoundsCenter.X, rebuilt.BoundsCenter.Y, rebuilt.BoundsCenter.Z), rebuilt.BoundsRadius);
        GeometryWriteResult geometry = GeometryWriter.Write(rebuilt.Pages, rebuilt.MaxMeshSlot); // also fills EncPage.WalkOff
        /* The template's own MOT slots (sectionFlags low byte, bit per slot): MotWriter only
           guarantees the battle slots the template carries, because retail omits one only for
           a card the game never plays it for (671, Exodia). 0 = no MOTs, i.e. not retail-like. */
        int templateMotionSlotsByte = (int)(ReadU32(originalMrg, 0x04) & 0xFF);
        MotWriter.Result motionResult = MotWriter.Write(rebuilt.Nodes.Count, rebuilt.Motions, 1, 0f, templateMotionSlotsByte);

        /* The TexTable count is NOT fixed to the template's: every texture-context record
           GeometryWriter emitted MUST be reachable from a dispatch entry, because the
           record's TEX0_1 placeholder is ZERO on disk and only becomes valid when
           lRhModel_SetupTexture@0x211f70 stamps it each frame. An unstamped record leaves
           TEX0=0 (TBP0=0/PSMCT32) and the GS samples the live framebuffer at VRAM page 0 -
           per-frame color flashing on the affected meshes. Both the per-frame stamper and
           the load-time absolutiser (SzModel_BindTextureFile, called from
           lSzModel_BindModelByAddr right after RhModel_BindAddress: absolutises rh2Off and
           postOff, RhText_BindAddress per block, zeroes blk+0xC) read the count from
           TexTable+0 and loop generically, and retail timeater ships 6 textures - so the
           table may legitimately GROW beyond the template's count.

           Growth strategy: slots >= template count get an RH2 built from a DONOR template
           block (slot i % originalTexCount) - re-encoded with the glb-supplied image when one
           exists, else the donor verbatim. If the grown layout would overflow the 1 MiB
           block, extra slots are shed again and their dispatch entries are REMAPPED onto an
           existing slot (wrong picture, but a stable one - never an unstamped record).
           SzModel_BindTextureFile skips TexBlocks with rh2Off==0, which would make the
           stamper read TEX0 from absolute address 0x30 - so a dispatched slot must always
           end up with a non-empty RH2. */
        int originalTexTableOffset = (int)ReadU32(originalMrg, 0x38);
        int originalTexCount = (int)ReadU32(originalMrg, originalTexTableOffset);
        /* Not every block's header+0x38 really points at a texture table: MODEL.MRG's
           EVENT2/31 (model id 65) reads 0x20000004 there, a tagged pointer, not a count. The
           extractor already treats a count outside 1..256 as "no texture table"
           (ModelExtractor.ParseTexTableForModel), so the assembler must agree, or OriginalRh2
           walks 500 million slots of someone else's data. */
        if (originalTexTableOffset <= 0 || originalTexCount < 0 || originalTexCount > 256) originalTexCount = 0;
        /* The table is sized to EXACTLY the slots the new model dispatches to - it shrinks
           as well as grows. A 6-texture template hosting a 4-texture model keeps 4 blocks:
           the two surplus template RH2 payloads (and their ANM entries) are dropped, which
           frees ~0x8530 each in the 1 MiB block. This is engine-safe because everything is
           count-driven from TexTable+0: SzModel_BindTextureFile loops count when
           absolutising, lRhModel_SetupTexture loops count when stamping, and the aux2
           texture-animation remap values are bounds-checked against the same count before
           use, so stale remap entries copied from the template simply never fire. Unused
           slots BELOW the highest used index are positional and must stay - they keep the
           template's RH2 verbatim. */
        int texCount = 0;
        foreach (var (texIndex, _) in geometry.TextureDispatch)
            if (texIndex + 1 > texCount)
                texCount = texIndex + 1;
        if (texCount == 0) texCount = Math.Min(originalTexCount, 1); // degenerate: no textured pages

        var inputByTexIndex = (textures ?? Array.Empty<TextureInput>()).Where(suppliedTexture => suppliedTexture != null)
            .GroupBy(suppliedTexture => suppliedTexture.TextureIndex).ToDictionary(textureGroup => textureGroup.Key, textureGroup => textureGroup.First());

        /* UV-atlas composites for merged texture slots: RebuildPipeline.ApplyTexMerges
           retargeted excess slots' pages onto base slots with V remapped into vertical
           bands; here the member images are stacked into one canvas (band k of n, top to
           bottom - glTF v=0 is the top row) and re-encoded into the base slot's template
           RH2. A member without a supplied image gets a neutral grey band; if no member
           supplied an image the base keeps the template verbatim. */
        foreach (var (baseSlot, members) in rebuilt.TexMerges)
        {
            int memberCount = members.Count;
            if (memberCount == 0) continue;
            var memberInputs = new TextureInput?[memberCount];
            bool anyMemberHasImage = false;
            for (int k = 0; k < memberCount; k++)
                if (inputByTexIndex.TryGetValue(members[k], out var foundInput) && foundInput.Rgba != null && foundInput.Width > 0 && foundInput.Height > 0)
                {
                    memberInputs[k] = foundInput;
                    anyMemberHasImage = true;
                }
            if (!anyMemberHasImage) continue;

            int canvasWidth = 0, bandHeight = 0;
            foreach (var memberInput in memberInputs)
                if (memberInput != null)
                {
                    canvasWidth = Math.Max(canvasWidth, memberInput.Width);
                    bandHeight = Math.Max(bandHeight, memberInput.Height);
                }
            var canvas = new byte[canvasWidth * bandHeight * memberCount * 4];
            for (int k = 0; k < memberCount; k++)
            {
                var sourceInput = memberInputs[k];
                for (int y = 0; y < bandHeight; y++)
                {
                    int rowBase = ((k * bandHeight + y) * canvasWidth) * 4;
                    for (int x = 0; x < canvasWidth; x++)
                    {
                        int destinationIndex = rowBase + x * 4;
                        if (sourceInput == null)
                        {
                            canvas[destinationIndex] = canvas[destinationIndex + 1] = canvas[destinationIndex + 2] = 128;
                            canvas[destinationIndex + 3] = 255;
                            continue;
                        }
                        int sourceX = canvasWidth == sourceInput.Width ? x : x * sourceInput.Width / canvasWidth;
                        int sourceY = bandHeight == sourceInput.Height ? y : y * sourceInput.Height / bandHeight;
                        int sourceIndex = (sourceY * sourceInput.Width + sourceX) * 4;
                        canvas[destinationIndex] = sourceInput.Rgba![sourceIndex];
                        canvas[destinationIndex + 1] = sourceInput.Rgba[sourceIndex + 1];
                        canvas[destinationIndex + 2] = sourceInput.Rgba[sourceIndex + 2];
                        canvas[destinationIndex + 3] = sourceInput.Rgba[sourceIndex + 3];
                    }
                }
            }
            inputByTexIndex[baseSlot] = new TextureInput { TextureIndex = baseSlot, Rgba = canvas, Width = canvasWidth, Height = bandHeight * memberCount };
        }

        ReadOnlySpan<byte> OriginalRh2(int slot)
        {
            if (slot < 0 || slot >= originalTexCount) return ReadOnlySpan<byte>.Empty;
            int blockOffset = originalTexTableOffset + 0x10 + slot * 16;
            int rh2Offset = (int)ReadU32(originalMrg, blockOffset);
            if (rh2Offset <= 0) return ReadOnlySpan<byte>.Empty;
            return originalMrg.AsSpan(rh2Offset, (int)ReadU32(originalMrg, rh2Offset + 8));
        }

        var rh2 = new byte[texCount][];
        var anm = new byte[texCount][];
        var usedNative = new bool[texCount];
        for (int i = 0; i < texCount; i++)
        {
            // the template's own slot for i < originalTexCount, wrapped around for extras
            int donorSlot = originalTexCount > 0 ? i % originalTexCount : -1;
            var donor = OriginalRh2(i < originalTexCount ? i : donorSlot);
            if (donor.IsEmpty && originalTexCount > 0) // wrap hit an empty slot
                for (int k = 0; k < originalTexCount && donor.IsEmpty; k++)
                    donor = OriginalRh2(k);

            if (inputByTexIndex.TryGetValue(i, out var textureInput) && textureInput.Rgba != null && textureInput.Width > 0 && textureInput.Height > 0)
            {
                if (textureInput.AnimationFrameCount > 1)
                {
                    /* Sprite sheets must land at EXACTLY their own packed size (already
                       POT/128/64-aligned, see GlbImporter's packer) - never run through the
                       normal donor-fit/ChooseTarget path, which independently computes a
                       POT target from the whole sheet's width and would stretch it,
                       shifting every frame's cell boundary off-grid. */
                    rh2[i] = Rh2Encoder.BuildNative(textureInput.Rgba, textureInput.Width, textureInput.Height, textureInput.Width, textureInput.Height);
                    usedNative[i] = true;
                }
                else if (textureInput.AnimationRecords is { Length: > 0 } && textureInput.AnimRecordsInImagePixels)
                {
                    // Image-space records: a native PSMT8 build, never the donor's size or
                    // format, so ScaleTexAnimRecords below knows the texel grid they land on.
                    var (nativeWidth, nativeHeight) = Rh2Encoder.ChooseTarget(textureInput.Width, textureInput.Height, MaxTextureDim);
                    rh2[i] = Rh2Encoder.BuildNative(textureInput.Rgba, textureInput.Width, textureInput.Height, nativeWidth, nativeHeight);
                    usedNative[i] = true;
                }
                else
                {
                    rh2[i] = EncodeTexture(donor, textureInput.Rgba, textureInput.Width, textureInput.Height, ownSizeTextures, out usedNative[i]);
                }
            }
            else
            {
                /* No picture supplied: a flat white texture at the smallest native size
                   (128x64 PSMT8, ~9 KB), not the donor's size (often 32 KB+), so no stale
                   picture is inherited. */
                rh2[i] = Rh2Encoder.BuildNative(CreateNeutralRgba(MinimumTextureWidth, MinimumTextureHeight), MinimumTextureWidth, MinimumTextureHeight,
                    MinimumTextureWidth, MinimumTextureHeight);
            }

            // A custom flipbook from the glb takes priority. The template's own ANM is never carried
            // over (it would bleed into an unrelated glb).
            if (inputByTexIndex.TryGetValue(i, out var anmTextureInput) && anmTextureInput.AnimationFrameCount > 1)
            {
                anm[i] = BuildCustomTexAnimEntry(anmTextureInput.AnimationFrameCount, anmTextureInput.AnimationColumns, anmTextureInput.AnimationRows,
                    anmTextureInput.AnimationBlockWidth, anmTextureInput.AnimationBlockHeight, anmTextureInput.AnimationTicksPerFrame);
            }
            else if (anmTextureInput?.AnimationRecords is { Length: > 0 } records)
            {
                // The slot's own records carried on the glb (an extracted model's retail animation),
                // not whatever sits in this template slot.
                anm[i] = records;
            }
            else
            {
                anm[i] = Array.Empty<byte>();
            }
        }

        /* GS page cap (custom models): SzModel_LoadTexture_Pipe @ 0x1EA2A0 uploads every texture
           of the model on each draw, back to back from RhBase_GetUserGsAddress, one 8 KB page per
           RH2 section, with no limit check: too many pages overwrite the GS memory past them and
           the screen flashes when the model is drawn (45 pages did). The most a playable retail
           monster uses is 31 (Electromagnetic Bagworm; Summoned Lord Exodia's 35 is not a
           playable card), so halve the largest supplied texture until the model fits that. */
        if (ownSizeTextures)
        {
            var pageFloor = new bool[texCount];
            while (TexturePages(rh2, texCount) > MaxModelTexturePages)
            {
                int largestIndex = -1;
                for (int i = 0; i < texCount; i++)
                    if (!pageFloor[i] && inputByTexIndex.TryGetValue(i, out var candidate) && candidate.Rgba != null && candidate.AnimationFrameCount <= 1 &&
                        !(candidate.AnimRecordsInImagePixels && candidate.AnimationRecords != null) &&
                        (largestIndex < 0 || Rh2Pages(rh2[i]) > Rh2Pages(rh2[largestIndex])))
                        largestIndex = i;
                if (largestIndex < 0) break; // every supplied texture is at the minimum
                var largestInput = inputByTexIndex[largestIndex];
                var (decodedWidth, decodedHeight) = DonorDecodedDims(rh2[largestIndex]);
                int halvedWidth = Math.Max(MinimumTextureWidth, Rh2Encoder.NextPot(decodedWidth) / 2);
                int halvedHeight = Math.Max(MinimumTextureHeight, Rh2Encoder.NextPot(decodedHeight) / 2);
                var smallerRh2 = Rh2Encoder.BuildNative(largestInput.Rgba!, largestInput.Width, largestInput.Height, halvedWidth, halvedHeight);
                if (Rh2Pages(smallerRh2) >= Rh2Pages(rh2[largestIndex])) { pageFloor[largestIndex] = true; continue; }
                rh2[largestIndex] = smallerRh2;
                usedNative[largestIndex] = true;
                result.HalvedForPages++;
            }
        }
        result.TexturePages = TexturePages(rh2, texCount);

        /* aux0/aux1 are LAYOUT-DEPENDENT: per-frame fixup lists for lRhModel_DynamicAddressBind
           (offsets of every bone-bind d1 word + the opening-tag ADDR inside Section1/Section1Alt).
           GeometryWriter regenerates them for the new Section1 layout; copying the originals
           verbatim leaves the DMA chain unbound -> VIF1 stall (black screen).
           aux2's consumer is unknown; it is zero-filled in retail and kept verbatim. */
        byte[] aux0 = geometry.Aux0;
        byte[] aux1 = geometry.Aux1;
        byte[] aux2 = CopyRegion(originalMrg, 0x58, 0x5C);
        /* aux2 +0x00..0x7F = 32 option-object pointers to lists of Section1 offsets that
           lRhModel_SetupOptionObject@0x212170 stamps with NOP tags per frame - layout-
           dependent, so zero them (optional geometry stays always visible). The rest of
           aux2 (default mask, texture remap, anim-texture index) is layout-independent
           config consumed by lRhModel_SetupTexture and is kept verbatim. Both sample
           retail models ship with these pointers already zero. */
        for (int i = 0; i < 0x80 && i < aux2.Length; i++) aux2[i] = 0;

        byte[] earlyPostMotionChain = CapturePostMotChain(originalMrg);

        int EstimateTotalSize(int textureCount)
        {
            int cursorOffset = HeaderPreambleEnd;

            int AppendBlock(int blockLength)
            {
                if (blockLength > 0) cursorOffset = ((cursorOffset + 0xF) & ~0xF) + blockLength;
                return cursorOffset;
            }

            AppendBlock(nodeTree.Length);
            AppendBlock(geometry.Section1.Length);
            AppendBlock(geometry.Section2.Length);
            AppendBlock(geometry.Section1Alt.Length);
            AppendBlock(geometry.Section2Alt.Length);
            AppendBlock(geometry.RelocWalk.Length);
            AppendBlock(Align16(0x10 + textureCount * 16 + textureCount * 8 + geometry.TextureDispatch.Count * 4)); // texTable
            AppendBlock(aux0.Length);
            AppendBlock(aux1.Length);
            AppendBlock(aux2.Length);
            for (int i = 0; i < textureCount; i++) AppendBlock(rh2[i].Length);
            for (int i = 0; i < textureCount; i++) AppendBlock(anm[i].Length);
            AppendBlock(motionResult.Blocks.Length);
            AppendBlock(earlyPostMotionChain.Length);
            return cursorOffset;
        }

        /* First fallback: shrink the synthesised battle-slot clones. Clones are filler (MotWriter,
           BATTLE-SLOT GUARANTEE), so they are traded for headroom before anything the user
           authored. Progressively decimate their keys, ending with a static pose (one key per
           track). Card 671's template has no slots 4-6 so it never clones; a custom glb over a
           fuller template can. */
        if (EstimateTotalSize(texCount) > blockSize && motionResult.Clones.Count > 0)
        {
            foreach (int stride in new[] { 2, 4, 8, 16, 32, MotWriter.StaticPose })
            {
                motionResult = MotWriter.Write(rebuilt.Nodes.Count, rebuilt.Motions, stride, 0f, templateMotionSlotsByte);
                if (EstimateTotalSize(texCount) <= blockSize) break;
            }
        }

        /* Overflow reduction: ask the caller before trading fidelity for headroom. The larger of
           {texture, animation} - by raw byte share of the budget - is offered first; when that
           lever alone cannot free enough, the other one is offered as well. */
        if (EstimateTotalSize(texCount) > blockSize)
        {
            int textureBytesBeforeReduction = 0;
            for (int i = 0; i < texCount; i++) textureBytesBeforeReduction += rh2[i].Length;
            var reductionOrder = textureBytesBeforeReduction > motionResult.Blocks.Length
                ? new[] { OverflowCategory.Texture, OverflowCategory.Animation }
                : new[] { OverflowCategory.Animation, OverflowCategory.Texture };
            foreach (var category in reductionOrder)
            {
                int totalBeforeReduction = EstimateTotalSize(texCount);
                if (totalBeforeReduction <= blockSize) break; // the first lever already made room
                int categoryBytes = 0;
                if (category == OverflowCategory.Texture)
                    for (int i = 0; i < texCount; i++) categoryBytes += rh2[i].Length;
                else
                    categoryBytes = motionResult.Blocks.Length;
                bool shouldApply = confirmReduction(category, categoryBytes, totalBeforeReduction, blockSize);
                if (!shouldApply) break; // declined: don't go on to offer the other lever
                if (category == OverflowCategory.Texture) ReduceTextures();
                else ReduceMotion();
            }
        }

        // Animation lever: refit rotation keys with a looser tolerance (2 BAMS is 0.011 deg, 32 is
        // 0.18 deg). Clones stay as the automatic step left them.
        void ReduceMotion()
        {
            int cloneStride = 1;
            if (motionResult.Clones.Count > 0)
                cloneStride = MotWriter.StaticPose; // the automatic step already ran out
            foreach (float toleranceBams in new[] { 2f, 4f, 8f, 16f, 32f })
            {
                motionResult = MotWriter.Write(rebuilt.Nodes.Count, rebuilt.Motions, cloneStride, toleranceBams, templateMotionSlotsByte);
                if (EstimateTotalSize(texCount) <= blockSize) break;
            }
        }

        // Texture lever: shrinks textures until the block fits, keeping a valid (lower-res) render.
        // Falls through to Place()'s overflow if even 128x64 everywhere is too big.
        void ReduceTextures()
        {
            // 1. native slots back to the donor-fit encode, where smaller
            while (EstimateTotalSize(texCount) > blockSize)
            {
                int largestIndex = -1, largestLength = -1;
                for (int i = 0; i < texCount; i++)
                    if (usedNative[i] && rh2[i].Length > largestLength &&
                        !(inputByTexIndex.TryGetValue(i, out var candidate) && candidate.AnimRecordsInImagePixels && candidate.AnimationRecords != null))
                    {
                        largestLength = rh2[i].Length;
                        largestIndex = i;
                    }
                if (largestIndex < 0) break; // nothing native left to downgrade
                usedNative[largestIndex] = false;

                int donorSlot = largestIndex < originalTexCount ? largestIndex : (originalTexCount > 0 ? largestIndex % originalTexCount : -1);
                var donor = OriginalRh2(donorSlot);
                if (donor.IsEmpty && originalTexCount > 0)
                    for (int k = 0; k < originalTexCount && donor.IsEmpty; k++)
                        donor = OriginalRh2(k);
                if (donor.IsEmpty || donor.Length >= rh2[largestIndex].Length) continue;
                rh2[largestIndex] = inputByTexIndex.TryGetValue(largestIndex, out var rebuildInput) && rebuildInput.Rgba != null
                    ? Rh2Encoder.Encode(donor, rebuildInput.Rgba, rebuildInput.Width, rebuildInput.Height)
                    : donor.ToArray();
            }

            // 2. halve the largest supplied texture, down to 128x64, until the block fits.
            // Sprite sheets keep their size: their cell grid is in texels.
            var atMinimumSize = new bool[texCount];
            while (EstimateTotalSize(texCount) > blockSize)
            {
                int largestIndex = -1;
                for (int i = 0; i < texCount; i++)
                    if (!atMinimumSize[i] && inputByTexIndex.TryGetValue(i, out var candidate) && candidate.Rgba != null && candidate.AnimationFrameCount <= 1 &&
                        (largestIndex < 0 || rh2[i].Length > rh2[largestIndex].Length))
                        largestIndex = i;
                if (largestIndex < 0) break; // every supplied texture is at the minimum
                var largestInput = inputByTexIndex[largestIndex];
                var (decodedWidth, decodedHeight) = DonorDecodedDims(rh2[largestIndex]);
                int halvedWidth = Math.Max(MinimumTextureWidth, Rh2Encoder.NextPot(decodedWidth) / 2);
                int halvedHeight = Math.Max(MinimumTextureHeight, Rh2Encoder.NextPot(decodedHeight) / 2);
                var smallerRh2 = Rh2Encoder.BuildNative(largestInput.Rgba!, largestInput.Width, largestInput.Height, halvedWidth, halvedHeight);
                if (smallerRh2.Length >= rh2[largestIndex].Length) { atMinimumSize[largestIndex] = true; continue; }
                rh2[largestIndex] = smallerRh2;
            }
        }

        // image-space records follow their texture to its final (possibly halved) size
        for (int i = 0; i < texCount; i++)
            if (inputByTexIndex.TryGetValue(i, out var recordInput) && recordInput.AnimRecordsInImagePixels &&
                recordInput.AnimationRecords != null && ReferenceEquals(anm[i], recordInput.AnimationRecords) && rh2[i].Length > 0)
            {
                var (finalWidth, finalHeight) = DonorDecodedDims(rh2[i]);
                anm[i] = ScaleTexAnimRecords(recordInput.AnimationRecords, recordInput.Width, recordInput.Height, finalWidth, finalHeight);
            }

        while (texCount > originalTexCount && EstimateTotalSize(texCount) > blockSize) texCount--;
        var shed = result.ShedTextureSlots;
        if (texCount != rh2.Length)
        {
            Array.Resize(ref rh2, texCount);
            Array.Resize(ref anm, texCount);
        }

        // Dispatch remap: every entry must land on a slot with a real RH2.
        int fallbackSlot = -1;
        for (int i = 0; i < texCount; i++)
            if (rh2[i].Length > 0)
            {
                fallbackSlot = i;
                break;
            }
        var dispatch = new List<(int TextureIndex, uint Entry)>(geometry.TextureDispatch.Count);
        foreach (var (dispatchTexIndex, entry) in geometry.TextureDispatch)
        {
            int remappedTexIndex = dispatchTexIndex;
            if (remappedTexIndex >= texCount || rh2[remappedTexIndex].Length == 0)
            {
                int wrapped = texCount > 0 ? remappedTexIndex % texCount : -1;
                remappedTexIndex = (wrapped >= 0 && rh2[wrapped].Length > 0) ? wrapped : fallbackSlot;
                if (dispatchTexIndex >= texCount && remappedTexIndex >= 0 && !shed.Contains((dispatchTexIndex, remappedTexIndex))) shed.Add((dispatchTexIndex, remappedTexIndex));
            }
            if (remappedTexIndex < 0)
            {
                /* No donor RH2 at all. MODEL.MRG's EVENT2/31 (model id 65) is such a block:
                   header+0x38 holds a tagged pointer, not a texture table, so it has neither a
                   table nor a payload. A textureless import belongs on it and must pass
                   straight through with no table and no dispatch entry, exactly like retail;
                   only an import that actually brings pixels needs a donor to encode into. */
                bool suppliesPixels = false;
                foreach (var textureEntry in inputByTexIndex)
                    if (textureEntry.Value.Rgba != null) { suppliesPixels = true; break; }
                if (suppliesPixels)
                    throw new InvalidOperationException(
                        "this template model carries no texture table and no RH2 texture payload, " +
                        "so there is no donor block to encode the import's textures into (RH2 " +
                        "synthesis from scratch is not supported) - import a glb with no textures " +
                        "over it, or pick a template that has at least one texture");
                continue;
            }
            dispatch.Add((remappedTexIndex, entry));
        }

        // Offsets are 16-aligned; header+preamble is copied first.
        var blockBytes = new byte[blockSize];
        Array.Copy(originalMrg, 0, blockBytes, 0, Math.Min(HeaderPreambleEnd, originalMrg.Length));

        int cursor = HeaderPreambleEnd;

        int Place(byte[] bytes, string label)
        {
            int placedOffset = Align16(cursor);
            cursor = placedOffset + bytes.Length;
            if (cursor > blockBytes.Length)
            {
                /* Report, never throw. The budget is the monster MRG's 1 MiB slot for a monster
                   import, but a MODEL.MRG sub-model's own slot (a few KB upwards) for a pack
                   import, and a pack model that misses its slot by a few bytes must come back as
                   a complete block with a clean "over by N B" (the slot check in
                   ModelMrg.Build / the caller's own size compare) instead of dying here
                   with a half-assembled buffer. Grow and keep going; OverflowBytes and
                   OverflowLabel record how far over the budget the finished block is. */
                Array.Resize(ref blockBytes, cursor);
                if (result.OverflowBytes == 0) result.OverflowLabel = label;
                result.OverflowBytes = cursor - blockSize;
            }
            Array.Copy(bytes, 0, blockBytes, placedOffset, bytes.Length);
            return placedOffset;
        }

        /* Sections 0..9 in header order, each one's size padded to the next, so they tile
           0xB0 .. header[0x08] exactly as on all 683 retail models (NOTES/models.md, Header).
           An empty section sits at the running cursor with size 0, as retail's do. */
        int PlaceSection(byte[] bytes, string label)
        {
            if (bytes.Length == 0) return cursor = Align16(cursor);
            int placedOffset = Place(bytes, label);
            cursor = Align16(cursor);
            return placedOffset;
        }

        int nodeTreeOffset = PlaceSection(nodeTree, "nodeTree");
        int section1Offset = PlaceSection(geometry.Section1, "section1");
        int section2Offset = PlaceSection(geometry.Section2, "section2");
        int section1AltOffset = PlaceSection(geometry.Section1Alt, "section1Alt");
        int section2AltOffset = PlaceSection(geometry.Section2Alt, "section2Alt");

        // texTable is filled in after the rh2/anm offsets are known; reserve its size now.
        byte[] texTable = BuildTexTablePlaceholder(texCount, dispatch.Count);
        int texTableOffset = PlaceSection(texTable, "texTable");
        int aux0Offset = PlaceSection(aux0, "aux0");
        int aux1Offset = PlaceSection(aux1, "aux1");
        int relocWalkOffset = PlaceSection(geometry.RelocWalk, "relocWalk");
        int aux2Offset = PlaceSection(aux2, "aux2");
        int modelEnd = cursor;

        var rh2Offsets = new int[texCount];
        var anmOffsets = new int[texCount];
        for (int i = 0; i < texCount; i++)
            if (rh2[i].Length > 0)
                rh2Offsets[i] = Place(rh2[i], $"rh2[{i}]");
        for (int i = 0; i < texCount; i++)
            if (anm[i].Length > 0)
                anmOffsets[i] = Place(anm[i], $"anm[{i}]");

        /* header[0x0C] trailing-region chain: lSzModel_BindModelByAddr@0x1f0500 walks a cursor
           starting at header[0x0C], driven by sectionFlags: bits 0-7 = embedded MOT blocks
           (advance by size@+4), bit 8/10 = fixed-0x8000 regions, bit 9 and bits 11-18 =
           embedded RhText RH2 files (advance by size@+8, RhText_BindAddress relocates them in
           place), bits 19/20 = align16(size@+8) regions, bit 21 = final tail region (no size).
           Retail monsters carry flags 0x80383875: MOTs + 3 effect textures + bit19/20/21
           regions. We replace ONLY the MOT part; everything else is captured verbatim and
           re-placed contiguously after our MOTs. header[0x0C] must point at the chain even with
           zero motions, otherwise the loader walks the RH0 header itself and RhText relocation
           corrupts the model.

           With neither MOT blocks nor post-mot chain content, header[0x0C] must hold the
           cursor (the real end of the placed block), never 0: 0 is not "no chain" to any
           consumer - the engine's walker (cur = blockBase + header[0x0C]) and ComputeBlockEnd
           use the same formula unconditionally, so 0 makes the computed end equal the block's
           own start (a phantom zero-length block). This case is most custom GLBs. */
        byte[] postMotionChain = earlyPostMotionChain;
        int motionOffset;
        if (motionResult.Blocks.Length > 0)
        {
            motionOffset = Place(motionResult.Blocks, "motBlocks");
            if (postMotionChain.Length > 0) Place(postMotionChain, "postMot"); // contiguous: cursor flows from MOTs into it
        }
        else if (postMotionChain.Length > 0)
        {
            motionOffset = Place(postMotionChain, "postMot");
        }
        else
        {
            motionOffset = cursor; // no chain at all: point at the real end of content, not 0
        }

        FillTexTable(blockBytes, texTableOffset, texCount, dispatch, rh2Offsets, anmOffsets);

        WriteU32(blockBytes, 0x04, ((uint)ReadU32(originalMrg, 0x04) & 0xFFFFFF00u) | (uint)(motionResult.SectionFlagsByte & 0xFF)); // keep upper flag bits
        WriteU32(blockBytes, 0x08, (uint)modelEnd);
        WriteU32(blockBytes, 0x0C, (uint)motionOffset);
        int[] sectionOffsets = { nodeTreeOffset, section1Offset, section2Offset, section1AltOffset, section2AltOffset,
                         texTableOffset, aux0Offset, aux1Offset, relocWalkOffset, aux2Offset, modelEnd };
        for (int k = 0; k < 10; k++)
        {
            WriteU32(blockBytes, 0x10 + 8 * k, (uint)sectionOffsets[k]);
            WriteU32(blockBytes, 0x14 + 8 * k, (uint)(sectionOffsets[k + 1] - sectionOffsets[k]));
        }
        WriteU32(blockBytes, 0x60, 0);
        WriteF32(blockBytes, 0x64, rebuilt.AnimTransScale);

        /* Validate the header[0x0C] region chain is reachable. OverlayB (sectionFlags bit 0x400)
           and the effect/camera-motion regions are bound by lSzModel_BindModelByAddr@0x1f0500
           walking the chain rooted at header[0x0C]. If MOT replacement shifted the chain so a
           region stop lands on the wrong offset, OverlayB points at garbage and SzModel_BattleSeq
           spawns its particle effect at world origin. Re-walk the just-written block with the
           engine's logic and fail the build rather than ship a model that spawns at (0,0,0). */
        ValidateRegionChain(blockBytes, cursor, motionResult.SectionFlagsByte);

        if (trimToContent)
        {
            /* cursor holds the true end of all placed content (every Place() call advances it
               by exactly what it wrote, 16-aligned). A MODEL.MRG-style variable pack has no
               fixed slot size to pad out to, so return only the meaningful bytes; blockSize
               is then only the budget OverflowBytes is measured against. */
            var trimmed = new byte[cursor];
            Array.Copy(blockBytes, 0, trimmed, 0, cursor);
            blockBytes = trimmed;
        }
        result.Block = blockBytes;
        result.MotionClones = motionResult.Clones;
        return result;
    }

    /// Computes the true end (one-past-last-byte) of the RH0 block starting at
    /// <paramref name="blockBase"/> within <paramref name="bytes"/>, by walking the
    /// header[0x0C]-rooted chain (the same one CapturePostMotChain decodes). Shared so the
    /// MODEL.MRG archive (disc/ModelMrg.cs) and the single-block extractor agree on block
    /// boundaries. <paramref name="postMotStart"/> receives the offset where the post-mot-chain
    /// regions begin (right after the original embedded MOTs, bits 0-7), which is
    /// CapturePostMotChain's capture start. Returns -1 if this is not a valid RH0 header (a
    /// false-positive magic match, not a real block).
    internal static long ComputeBlockEnd(ReadOnlySpan<byte> bytes, long blockBase, out long postMotStart)
    {
        postMotStart = -1;
        if (blockBase < 0 || blockBase + 0x10 > bytes.Length) return -1;
        if (ReadU32(bytes, (int)blockBase) != Rh0Magic) return -1;

        uint sectionFlags = ReadU32(bytes, (int)blockBase + 0x04);
        long chainCursor = blockBase + ReadU32(bytes, (int)blockBase + 0x0C);
        if (chainCursor < blockBase || chainCursor > bytes.Length) return -1;

        for (int slot = 0; slot < 8; slot++) // bits 0-7: embedded MOT blocks
            if ((sectionFlags & (1u << slot)) != 0)
            {
                if (chainCursor + 8 > bytes.Length) return -1;
                chainCursor += ReadU32(bytes, (int)chainCursor + 4);
            }
        postMotStart = chainCursor;
        if ((sectionFlags & 0x100u) != 0) chainCursor += 0x8000; // bit 8: fixed-size region
        if ((sectionFlags & 0x200u) != 0) { if (chainCursor + 12 > bytes.Length) return -1; chainCursor += ReadU32(bytes, (int)chainCursor + 8); } // bit 9: RhText
        if ((sectionFlags & 0x400u) != 0) chainCursor += 0x8000; // bit 10: fixed-size region
        for (int i = 0; i < 8; i++) // bits 11-18: RhText blocks
            if ((sectionFlags & (1u << (11 + i))) != 0)
            {
                if (chainCursor + 12 > bytes.Length) return -1;
                chainCursor += ReadU32(bytes, (int)chainCursor + 8);
            }
        if ((sectionFlags & 0x80000u) != 0) { if (chainCursor + 12 > bytes.Length) return -1; chainCursor += (ReadU32(bytes, (int)chainCursor + 8) + 0xF) & ~0xFu; } // bit 19
        if ((sectionFlags & 0x100000u) != 0) { if (chainCursor + 12 > bytes.Length) return -1; chainCursor += (ReadU32(bytes, (int)chainCursor + 8) + 0xF) & ~0xFu; } // bit 20
        if ((sectionFlags & 0x200000u) != 0)
        {
            /* bit 21: final region with no stored size - needs the caller's true container
               end to trim trailing zeros against (CapturePostMotChain has it via
               orig.Length; pack scanning does not, and this bit hasn't been observed in
               MODEL.MRG). Signal "open-ended" with a sentinel the pack scanner treats as
               "cannot determine, stop scanning". */
            return long.MaxValue;
        }
        return Math.Min(chainCursor, bytes.Length);
    }

    /// Post-assembly sanity check on the header[0x0C] trailing-region chain: walks the
    /// freshly-written block like the engine's binder (lSzModel_BindModelByAddr@0x1f0500 /
    /// ComputeBlockEnd) and throws if anything the loader would dereference is out of range.
    /// <paramref name="contentEnd"/> is the assembler's cursor (true one-past-last placed
    /// byte); <paramref name="motByte"/> is the sectionFlags low byte we wrote (bits 0-7 =
    /// embedded MOT slots).
    ///
    /// Checks, in order:
    ///   * header[0x0C] (chain root) sits inside placed content,
    ///   * each embedded MOT slot bit set in bits 0-7 has a real MOT magic at the walked
    ///     position (catches a sectionFlags byte that desynced from the emitted MOT blocks),
    ///   * the full walk via ComputeBlockEnd succeeds (return != -1: no region size ran off
    ///     the end), and the computed end does not exceed the block.
    /// A bit-21 open-ended tail (ComputeBlockEnd returns long.MaxValue) is accepted: it is
    /// trimmed against the block length as CapturePostMotChain does, so it cannot over-run.
    private static void ValidateRegionChain(byte[] block, int contentEnd, int motByte)
    {
        uint sectionFlags = ReadU32(block, 0x04);
        long chainRoot = ReadU32(block, 0x0C);

        if (chainRoot < HeaderPreambleEnd || chainRoot > contentEnd)
            throw new InvalidOperationException(
                $"RH0 region chain root (header[0x0C]={chainRoot:X}) is outside placed content " +
                $"(0x{HeaderPreambleEnd:X}..0x{contentEnd:X}); OverlayB/effect binding would " +
                "dereference garbage and spawn battle effects at world origin.");

        // Each declared MOT slot (bits 0-7) must have a MOT block where the loader will look.
        long chainCursor = chainRoot;
        for (int slot = 0; slot < 8; slot++)
        {
            if ((sectionFlags & (1u << slot)) == 0) continue;
            if (chainCursor + 8 > block.Length)
                throw new InvalidOperationException(
                    $"RH0 MOT slot {slot} chain entry runs past the block end (cur=0x{chainCursor:X}).");
            if (ReadU32(block, (int)chainCursor) != MotWriter.Magic)
                throw new InvalidOperationException(
                    $"RH0 sectionFlags bit {slot} is set but no MOT magic is present at the " +
                    $"chain position 0x{chainCursor:X}. The sectionFlags low byte (0x{motByte & 0xFF:X2}) " +
                    "is out of sync with the emitted MOT blocks; SzModel_SetAnimIntr would " +
                    "null-fault and stall the 3D battle.");
            chainCursor += ReadU32(block, (int)chainCursor + 4);
        }

        // Full chain walk (MOTs + bits 8..21 regions).
        long blockEnd = ComputeBlockEnd(block, 0, out long postMotStart);
        if (blockEnd == -1)
            throw new InvalidOperationException(
                "RH0 region chain walk failed: a region size field points past the block end. " +
                "The header[0x0C] chain is malformed and the engine's binder would read out of " +
                "bounds (black screen / corrupt effects).");
        if (postMotStart < 0 || postMotStart > block.Length)
            throw new InvalidOperationException(
                $"RH0 post-MOT chain start (0x{postMotStart:X}) is out of range.");
        if (blockEnd != long.MaxValue && blockEnd > block.Length)
            throw new InvalidOperationException(
                $"RH0 region chain computed end (0x{blockEnd:X}) exceeds the block size " +
                $"(0x{block.Length:X}).");
    }

    private static byte[] CapturePostMotChain(byte[] originalMrg)
    {
        uint sectionFlags = ReadU32(originalMrg, 0x04);
        if ((sectionFlags & 0x003FFF00u) == 0) return Array.Empty<byte>();

        long regionEnd = ComputeBlockEnd(originalMrg, 0, out long regionStart);
        if (regionEnd == long.MaxValue)
        {
            // bit 21 (open-ended trailing region): trim trailing zeros against this block's own length.
            int trimmedEnd = originalMrg.Length;
            while (trimmedEnd > regionStart && originalMrg[trimmedEnd - 1] == 0) trimmedEnd--;
            regionEnd = Math.Max(regionStart, (trimmedEnd + 0xF) & ~0xF);
        }
        regionEnd = Math.Min(regionEnd, originalMrg.Length);
        if (regionEnd <= regionStart) return Array.Empty<byte>();
        var chainBytes = new byte[regionEnd - regionStart];
        Array.Copy(originalMrg, regionStart, chainBytes, 0, chainBytes.Length);
        return chainBytes;
    }

    // TexTable layout: count, perTexOff, 0, 0 | TexBlock[count] (16B) | TexDispatchDesc[count] (8B) | dispatch entries (u32).
    private static byte[] BuildTexTablePlaceholder(int textureCount, int dispatchCount)
    {
        int tableSize = 0x10 + textureCount * 16 + textureCount * 8 + dispatchCount * 4;
        return new byte[Align16(tableSize)];
    }

    private static void FillTexTable(byte[] blockBytes, int texTableOffset, int textureCount,
        IReadOnlyList<(int TextureIndex, uint Entry)> texDispatch, int[] rh2Offsets, int[] anmOffsets)
    {
        int blocksOffset = 0x10;
        int descriptorsOffset = blocksOffset + textureCount * 16;
        int dispatchEntriesOffset = descriptorsOffset + textureCount * 8;

        WriteU32(blockBytes, texTableOffset + 0x00, (uint)textureCount);
        WriteU32(blockBytes, texTableOffset + 0x04, (uint)descriptorsOffset); // perTexOff (rel TexTable)

        int dispatchCursor = texTableOffset + dispatchEntriesOffset; // absolute write cursor for dispatch entries
        for (int textureIndex = 0; textureIndex < textureCount; textureIndex++)
        {
            int blockOffset = texTableOffset + blocksOffset + textureIndex * 16;
            WriteU32(blockBytes, blockOffset + 0x00, (uint)(textureIndex < rh2Offsets.Length ? rh2Offsets[textureIndex] : 0)); // rh2Off (RH0-rel)
            WriteU32(blockBytes, blockOffset + 0x08, (uint)(textureIndex < anmOffsets.Length ? anmOffsets[textureIndex] : 0)); // postOff (RH0-rel)

            /* Dispatch entries: lRhModel_SetupTexture@0x211f70 copies 2 qwords (TEX0_1/TEX1_1
               from this texture's RH2+0x30) to Section1copy + (entry & 0x0FFFFFFF) EVERY frame
               (tag 0x2 = main copy, 0x4 = alt copy). The entries come from GeometryWriter: one
               per texture-context record, pointing at its TEX0_1 placeholder (record + 0x70).
               Emission order (main, then alt) is preserved. */
            var entries = new List<uint>();
            foreach (var (entryTexIndex, entry) in texDispatch)
                if (entryTexIndex == textureIndex)
                    entries.Add(entry);
            int descriptorOffset = texTableOffset + descriptorsOffset + textureIndex * 8;
            WriteU32(blockBytes, descriptorOffset + 0x00, (uint)entries.Count); // nDisp
            WriteU32(blockBytes, descriptorOffset + 0x04, (uint)(dispatchCursor - texTableOffset)); // dispOff (rel TexTable)
            foreach (var dispatchEntry in entries)
            {
                WriteU32(blockBytes, dispatchCursor, dispatchEntry);
                dispatchCursor += 4;
            }
        }
    }

    private static byte[] CopyRegion(byte[] bytes, int offField, int sizeField)
    {
        int regionOffset = (int)ReadU32(bytes, offField), regionSize = (int)ReadU32(bytes, sizeField);
        if (regionOffset <= 0 || regionSize <= 0 || regionOffset + regionSize > bytes.Length) return Array.Empty<byte>();
        var regionBytes = new byte[regionSize];
        Array.Copy(bytes, regionOffset, regionBytes, 0, regionSize);
        return regionBytes;
    }

    private static byte[] CreateNeutralRgba(int width, int height)
    {
        width = Math.Max(1, width);
        height = Math.Max(1, height);
        var rgba = new byte[width * height * 4];
        for (int i = 0; i < rgba.Length; i += 4)
        {
            rgba[i + 0] = 255;
            rgba[i + 1] = 255;
            rgba[i + 2] = 255;
            rgba[i + 3] = 255;
        }
        return rgba;
    }

    /* TexAnm entry (24 bytes), checked against SzModel_LoadTexAnim_Pipe @ 0x1EA410 (US) and its
       caller SzModel_LoadTexture_Pipe @ 0x1EA2A0 (DotR-PC NOTES/models.md, "Texture animation"):
         +00 flags: bit 0 last entry, bit 1 own clock (+14) instead of the motion frame,
             bits 2-4 mode, bits 5-7 direction (2 and 3 negate the cell index)
         +01 motion mask (bit k = active while motion slot k plays; 0xFF always)
         +02 grid: low nibble cols, high nibble rows (0 in either = entry skipped)
         +03 state: mode 0/1 current cell (signed byte); modes 2/3 cell << 2 | step, where the
             2-bit step must start at +1 or the ping-pong never moves
         +04 p0, +06 p1 (u16): modes 0-3 hold ticks per cell (p1 = ping-pong backwards)
         +08/+0A cell w/h, +0C/+0E src (sheet origin), +10/+12 dst, +14 own clock (runtime)
       Every draw, cell c is copied with a GS local->local transfer from
       src + (w * (c % cols), h * (c / cols)) onto dst inside the texture's own VRAM. The texture
       itself is re-uploaded on every draw first, so a copy never outlives its frame: src == dst
       == (0, 0) is fine, cell 0 needs no copy (the game skips it) and keeps frame 0's pixels.
       Paused or stoned models get no copies at all, i.e. frame 0.

       Custom imports get mode 1 LOOP on the own clock: flags 0x07 (last | own clock | 1 << 2),
       state 0, the cell advancing every ticksPerFrame draws. (Mode 3 would ping-pong.)
       Limits: cols and rows are nibbles (15 x 15 cells), and the loop's cell index is a signed
       byte, so at most 127 frames. */
    public const int MaxAnimFrames = 127;

    private static byte[] BuildCustomTexAnimEntry(int frameCount, int cols, int rows, int blockWidth, int blockHeight,
        int ticksPerFrame)
    {
        const int EntrySize = 0x18;
        frameCount = Math.Clamp(frameCount, 1, MaxAnimFrames);
        if (cols <= 0 || rows <= 0)
        {
            cols = frameCount;
            rows = 1;
        }
        cols = Math.Clamp(cols, 1, 15);
        rows = Math.Clamp(rows, 1, 15);
        var entryBytes = new byte[EntrySize];
        entryBytes[0] = 0x07;          // last | own clock | mode 1 (LOOP)
        entryBytes[1] = 0xFF;          // every motion
        // the loop runs over all cols * rows cells; spare cells of a partial last row repeat the
        // last frame (DecodeGlbTextures)
        entryBytes[2] = (byte)((cols & 0xF) | ((rows & 0xF) << 4));
        entryBytes[3] = 0;             // start on cell 0
        ushort ticks = (ushort)Math.Clamp(ticksPerFrame, 1, ushort.MaxValue);
        WriteU16(entryBytes, 4, ticks);   // p0
        WriteU16(entryBytes, 6, ticks);   // p1 (unused by LOOP)
        WriteU16(entryBytes, 8, (ushort)Math.Clamp(blockWidth, 1, ushort.MaxValue));
        WriteU16(entryBytes, 0xA, (ushort)Math.Clamp(blockHeight, 1, ushort.MaxValue));
        // src and dst (0, 0): the sheet starts at the cell the faces sample
        return entryBytes;
    }

    /* ownSize (custom models): never take the donor's size (it scaled a 64x64 image up to the
       donor's 256x128, 5 GS pages for 1; Alpha the Magnet Warrior over card 0: 45 pages). Native
       is used when ownSize, or when the source exceeds the donor's decoded dimensions or no donor exists. */
    private static byte[] EncodeTexture(ReadOnlySpan<byte> donor, byte[] rgba, int width, int height,
        bool ownSize, out bool wentNative)
    {
        wentNative = false;
        bool haveDonor = !donor.IsEmpty && donor.Length >= 0x60;
        if (haveDonor && !ownSize)
        {
            var (decodedWidth, decodedHeight) = DonorDecodedDims(donor);
            if (width <= decodedWidth && height <= decodedHeight)
                return Rh2Encoder.Encode(donor, rgba, width, height);
        }

        var (nativeWidth, nativeHeight) = Rh2Encoder.ChooseTarget(width, height, MaxTextureDim);
        wentNative = true;
        return Rh2Encoder.BuildNative(rgba, width, height, nativeWidth, nativeHeight);
    }

    // Scale every record's size/src/dst (u16 pairs at +8, +0xC, +0x10) from a imageWidth x imageHeight image
    // to the finalWidth x finalHeight texture it was encoded as. Same size: the records come back as they are.
    private static byte[] ScaleTexAnimRecords(byte[] records, int imageWidth, int imageHeight, int finalWidth, int finalHeight)
    {
        if (imageWidth == finalWidth && imageHeight == finalHeight) return records;
        var scaledRecords = (byte[])records.Clone();
        for (int recordOffset = 0; recordOffset + 0x18 <= scaledRecords.Length; recordOffset += 0x18)
            for (int fieldOffset = 0x08; fieldOffset <= 0x12; fieldOffset += 2)
            {
                bool isXField = (fieldOffset & 2) == 0; // +8/+C/+10 are x, +A/+E/+12 are y
                int value = ReadU16(scaledRecords, recordOffset + fieldOffset);
                int scaled = (int)Math.Round(value * (double)(isXField ? finalWidth : finalHeight) / (isXField ? imageWidth : imageHeight));
                WriteU16(scaledRecords, recordOffset + fieldOffset, (ushort)Math.Clamp(scaled, 0, 0xFFFF));
            }
        return scaledRecords;
    }

    // Decoded image dimensions a donor RH2 represents (PSMT4 decodes to half size).
    private static (int Width, int Height) DonorDecodedDims(ReadOnlySpan<byte> donor)
    {
        int psm = ReadU16(donor, 0x50);
        int width = ReadU16(donor, 0x54), height = ReadU16(donor, 0x56);
        return psm == 0x14 ? (Math.Max(width / 2, 1), Math.Max(height / 2, 1)) : (width, height);
    }

    private static int Align16(int value) => (value + (AlignmentBytes - 1)) & ~(AlignmentBytes - 1);

    // An RH2's section count (+0x58): SzText_Load_Pipe uploads one 8 KB GS page per section.
    private static int Rh2Pages(byte[] rh2)
    {
        if (rh2 == null || rh2.Length < 0x5A)
        {
            return 0;
        }
        return ReadU16(rh2, 0x58);
    }

    private static int TexturePages(byte[][] rh2, int textureCount)
    {
        int pages = 0;
        for (int i = 0; i < textureCount; i++)
        {
            pages += Rh2Pages(rh2[i]);
        }
        return pages;
    }
