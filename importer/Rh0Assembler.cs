using System.Buffers.Binary;

namespace DotrAssetModder;

// === Step 6.6 — RH0 assembler ========================================================
// Combines the rebuilt sub-blocks into a single 1 MiB RH0 by TEMPLATE-INJECT: the
// original .mrg is the base, its header preamble (0x00..nodeTree) and aux2 are
// preserved VERBATIM, and only the blocks we regenerate are re-laid-out, with every
// header offset / size and TexTable pointer fixed up.
//
// Why template-inject rather than synthesis: the RH0 header carries a fixed preamble
// (incl. model-scale floats at +0xA8 and sectionFlags upper bits) whose exact engine
// use isn't fully reversed. RhModel_BindAddress consumes relocWalk + the four section
// bases (all regenerated correctly), and relocates each page terminator's term1
// (0x30000000|sec2Off) in place - exactly what GeometryWriter emits.
//
// aux0/aux1 are NOT copied: they are the per-frame lRhModel_DynamicAddressBind@0x20dd00
// fixup lists (offsets of every bone-bind d1 word + the opening-tag ADDR), tied to the
// Section1/Section1Alt layout, and are regenerated by GeometryWriter. Copying the
// originals verbatim leaves the new chain unbound -> VIF1 stall (black screen).
// aux2's consumer is unknown; it is zero-filled in retail and kept verbatim.
//
// Block order: header+preamble | nodeTree | section1 | section2 | section1Alt |
// section2Alt | relocWalk | texTable | aux0 | aux1 | aux2 | RH2[*] | ANM[*] | MOT | pad.
// =====================================================================================

public static class Rh0Assembler
{
    public const uint Rh0Magic = 0x00304852;
    private const int HeaderPreambleEnd = 0xB0; // header (0x68) + fixed preamble; nodeTree starts here in stock models
    private const int Align = 16;

    public sealed class TextureInput
    {
        public int TexIdx;
        public byte[]? Rgba; // edited texture (null => keep the original RH2 verbatim)
        public int Width, Height;
    }

    public static byte[] Assemble(byte[] originalMrg, RebuildPipeline.Result rebuilt,
        IReadOnlyList<TextureInput>? textures = null, int blockSize = 0x100000,
        bool rebuildNative = false, int maxTexDim = 512)
    {
        if (U32(originalMrg, 0) != Rh0Magic) throw new InvalidOperationException("template is not an RH0");

        // ---- regenerate blocks ----
        byte[] nodeTree = NodeTreeWriter.Write(rebuilt.Nodes,
            (rebuilt.BoundsCenter.X, rebuilt.BoundsCenter.Y, rebuilt.BoundsCenter.Z), rebuilt.BoundsRadius);
        GeometryWriteResult geo = GeometryWriter.Write(rebuilt.Pages, rebuilt.MaxMeshSlot); // also fills EncPage.WalkOff
        var (motBlocks, motByte) = MotWriter.Write(rebuilt.Nodes.Count, rebuilt.Motions);

        // ---- textures: per TexTable entry, build RH2 + ANM ----
        // The TexTable count is NOT fixed to the template's: every texture-context record
        // GeometryWriter emitted MUST be reachable from a dispatch entry, because the
        // record's TEX0_1 placeholder is ZERO on disk and only becomes valid when
        // lRhModel_SetupTexture@0x20fda0 stamps it each frame. An unstamped record leaves
        // TEX0=0 (TBP0=0/PSMCT32) and the GS samples the live framebuffer at VRAM page 0 -
        // per-frame color flashing on the affected meshes. Both the per-frame stamper and
        // the load-time absolutiser (SzModel_BindTextureFile, called from
        // lSzModel_BindModelByAddr right after RhModel_BindAddress: absolutises rh2Off and
        // postOff, RhText_BindAddress per block, zeroes blk+0xC) read the count from
        // TexTable+0 and loop generically, and retail timeater ships 6 textures - so the
        // table may legitimately GROW beyond the template's count.
        //
        // Growth strategy: slots >= template count get an RH2 built from a DONOR template
        // block (slot i % origCount) - re-encoded with the glb-supplied image when one
        // exists, else the donor verbatim. If the grown layout would overflow the 1 MiB
        // block, extra slots are shed again and their dispatch entries are REMAPPED onto an
        // existing slot (wrong picture, but a stable one - never an unstamped record).
        // SzModel_BindTextureFile skips TexBlocks with rh2Off==0, which would make the
        // stamper read TEX0 from absolute address 0x30 - so a dispatched slot must always
        // end up with a non-empty RH2.
        int origTt = (int)U32(originalMrg, 0x38);
        int origCount = (int)U32(originalMrg, origTt);
        // The table is sized to EXACTLY the slots the new model dispatches to - it shrinks
        // as well as grows. A 6-texture template hosting a 4-texture model keeps 4 blocks:
        // the two surplus template RH2 payloads (and their ANM entries) are dropped, which
        // frees ~0x8530 each in the 1 MiB block. This is engine-safe because everything is
        // count-driven from TexTable+0: SzModel_BindTextureFile loops count when
        // absolutising, lRhModel_SetupTexture loops count when stamping, and the aux2
        // texture-animation remap values are bounds-checked against the same count before
        // use, so stale remap entries copied from the template simply never fire. Unused
        // slots BELOW the highest used index are positional and must stay - they keep the
        // template's RH2 verbatim.
        int texCount = 0;
        foreach (var (ti_, _) in geo.TexDispatch)
            if (ti_ + 1 > texCount)
                texCount = ti_ + 1;
        if (texCount == 0) texCount = Math.Min(origCount, 1); // degenerate: no textured pages

        var byTex = (textures ?? Array.Empty<TextureInput>()).Where(t => t != null)
            .GroupBy(t => t.TexIdx).ToDictionary(g => g.Key, g => g.First());

        // ---- UV-atlas composites for merged texture slots ----
        // RebuildPipeline.ApplyTexMerges retargeted excess slots' pages onto base slots
        // with V remapped into vertical bands; here the member images are stacked into one
        // canvas (band k of n, top to bottom — glTF v=0 is the top row) and re-encoded into
        // the base slot's template RH2. A member without a supplied image gets a neutral
        // grey band; if no member supplied an image the base keeps the template verbatim.
        foreach (var (baseSlot, members) in rebuilt.TexMerges)
        {
            int n = members.Count;
            if (n == 0) continue;
            var imgs = new TextureInput?[n];
            bool anyImg = false;
            for (int k = 0; k < n; k++)
                if (byTex.TryGetValue(members[k], out var t) && t.Rgba != null && t.Width > 0 && t.Height > 0)
                {
                    imgs[k] = t;
                    anyImg = true;
                }
            if (!anyImg) continue;

            int w = 0, bandH = 0;
            foreach (var t in imgs)
                if (t != null)
                {
                    w = Math.Max(w, t.Width);
                    bandH = Math.Max(bandH, t.Height);
                }
            var canvas = new byte[w * bandH * n * 4];
            for (int k = 0; k < n; k++)
            {
                var s = imgs[k];
                for (int y = 0; y < bandH; y++)
                {
                    int rowBase = ((k * bandH + y) * w) * 4;
                    for (int x = 0; x < w; x++)
                    {
                        int di = rowBase + x * 4;
                        if (s == null)
                        {
                            canvas[di] = canvas[di + 1] = canvas[di + 2] = 128;
                            canvas[di + 3] = 255;
                            continue;
                        }
                        int sx = w == s.Width ? x : x * s.Width / w;
                        int sy = bandH == s.Height ? y : y * s.Height / bandH;
                        int si = (sy * s.Width + sx) * 4;
                        canvas[di] = s.Rgba![si];
                        canvas[di + 1] = s.Rgba[si + 1];
                        canvas[di + 2] = s.Rgba[si + 2];
                        canvas[di + 3] = s.Rgba[si + 3];
                    }
                }
            }
            byTex[baseSlot] = new TextureInput { TexIdx = baseSlot, Rgba = canvas, Width = w, Height = bandH * n };
        }

        ReadOnlySpan<byte> OrigRh2(int slot)
        {
            if (slot < 0 || slot >= origCount) return ReadOnlySpan<byte>.Empty;
            int blk = origTt + 0x10 + slot * 16;
            int off = (int)U32(originalMrg, blk);
            if (off <= 0) return ReadOnlySpan<byte>.Empty;
            return originalMrg.AsSpan(off, (int)U32(originalMrg, off + 8));
        }

        var rh2 = new byte[texCount][];
        var anm = new byte[texCount][];
        var usedNative = new bool[texCount];
        for (int i = 0; i < texCount; i++)
        {
            // donor: the template's own slot for i < origCount, wrapped around for extras
            int donorSlot = origCount > 0 ? i % origCount : -1;
            var donor = OrigRh2(i < origCount ? i : donorSlot);
            if (donor.IsEmpty && origCount > 0) // wrap hit an empty slot
                for (int k = 0; k < origCount && donor.IsEmpty; k++)
                    donor = OrigRh2(k);

            if (byTex.TryGetValue(i, out var ti) && ti.Rgba != null && ti.Width > 0 && ti.Height > 0)
                rh2[i] = EncodeTexture(donor, ti.Rgba, ti.Width, ti.Height, rebuildNative, maxTexDim, out usedNative[i]);
            else
                rh2[i] = donor.ToArray(); // template texture verbatim

            // ANM (texture-animation frames) only exists for the template's own slots
            int postOff = i < origCount ? (int)U32(originalMrg, origTt + 0x10 + i * 16 + 8) : 0;
            anm[i] = postOff > 0 ? TexAnmWriter.ExtractEntries(originalMrg, postOff) : Array.Empty<byte>();
        }

        // ---- aux lists ----
        // aux0/aux1 are LAYOUT-DEPENDENT: per-frame fixup lists for lRhModel_DynamicAddressBind
        // (offsets of every bone-bind d1 word + the opening-tag ADDR inside Section1/Section1Alt).
        // They are regenerated by GeometryWriter to match the new Section1 layout; copying the
        // originals verbatim leaves the DMA chain unbound -> VIF1 stall (black screen).
        // aux2's consumer is unknown; it is zero-filled in retail and kept verbatim.
        byte[] aux0 = geo.Aux0;
        byte[] aux1 = geo.Aux1;
        byte[] aux2 = CopyRegion(originalMrg, 0x58, 0x5C);
        // aux2 +0x00..0x7F = 32 option-object pointers to lists of Section1 offsets that
        // lRhModel_SetupOptionObject@0x20ffa0 stamps with NOP tags per frame — layout-
        // dependent, so zero them (optional geometry stays always visible). The rest of
        // aux2 (default mask, texture remap, anim-texture index) is layout-independent
        // config consumed by lRhModel_SetupTexture and is kept verbatim. Both sample
        // retail models ship with these pointers already zero.
        for (int i = 0; i < 0x80 && i < aux2.Length; i++) aux2[i] = 0;

        // ---- shed extra texture slots that would overflow the 1 MiB block ----
        byte[] postMotEarly = CapturePostMotChain(originalMrg);

        int EstimateTotal(int count)
        {
            int c = HeaderPreambleEnd;

            int Add(int len)
            {
                if (len > 0) c = ((c + 0xF) & ~0xF) + len;
                return c;
            }

            Add(nodeTree.Length);
            Add(geo.Section1.Length);
            Add(geo.Section2.Length);
            Add(geo.Section1Alt.Length);
            Add(geo.Section2Alt.Length);
            Add(geo.RelocWalk.Length);
            Add(Align16(0x10 + count * 16 + count * 8 + geo.TexDispatch.Count * 4)); // texTable
            Add(aux0.Length);
            Add(aux1.Length);
            Add(aux2.Length);
            for (int i = 0; i < count; i++) Add(rh2[i].Length);
            for (int i = 0; i < count; i++) Add(anm[i].Length);
            Add(motBlocks.Length);
            Add(postMotEarly.Length);
            return c;
        }

        // ---- native-rebuild budget: downgrade oversized native slots to fit the block ----
        // BuildNative slots can dwarf the donor's footprint. For the fixed 1 MiB monster.mrg
        // block, if the layout would overflow, downgrade native slots (largest first) back to
        // the donor-fit Encode/verbatim path until it fits. This keeps a valid render (lower
        // res) instead of throwing; the proper "grow the archive" handling is Phase 2/3.
        if (rebuildNative)
        {
            while (EstimateTotal(texCount) > blockSize)
            {
                int big = -1, bigLen = -1;
                for (int i = 0; i < texCount; i++)
                    if (usedNative[i] && rh2[i].Length > bigLen)
                    {
                        bigLen = rh2[i].Length;
                        big = i;
                    }
                if (big < 0) break; // nothing native left to downgrade

                int dSlot = big < origCount ? big : (origCount > 0 ? big % origCount : -1);
                var donor = OrigRh2(dSlot);
                if (donor.IsEmpty && origCount > 0)
                    for (int k = 0; k < origCount && donor.IsEmpty; k++)
                        donor = OrigRh2(k);
                rh2[big] = (byTex.TryGetValue(big, out var t) && t.Rgba != null && !donor.IsEmpty)
                    ? Rh2Encoder.Encode(donor, t.Rgba, t.Width, t.Height)
                    : donor.ToArray();
                usedNative[big] = false;
            }
        }

        while (texCount > origCount && EstimateTotal(texCount) > blockSize) texCount--;
        if (texCount != rh2.Length)
        {
            Array.Resize(ref rh2, texCount);
            Array.Resize(ref anm, texCount);
        }

        // ---- dispatch remap: every entry must land on a slot with a real RH2 ----
        int fallbackSlot = -1;
        for (int i = 0; i < texCount; i++)
            if (rh2[i].Length > 0)
            {
                fallbackSlot = i;
                break;
            }
        var dispatch = new List<(int TexIdx, uint Entry)>(geo.TexDispatch.Count);
        foreach (var (ti_, entry) in geo.TexDispatch)
        {
            int t = ti_;
            if (t >= texCount || rh2[t].Length == 0)
            {
                int wrapped = texCount > 0 ? t % texCount : -1;
                t = (wrapped >= 0 && rh2[wrapped].Length > 0) ? wrapped : fallbackSlot;
            }
            if (t < 0)
                throw new InvalidOperationException(
                    "the template model carries no RH2 texture payloads, so there is no donor " +
                    "block to encode the import's textures into (RH2 synthesis from scratch is " +
                    "not supported) - inject over a template that has at least one texture");
            dispatch.Add((t, entry));
        }

        // ---- assign offsets (16-aligned), header+preamble copied first ----
        var outBuf = new byte[blockSize];
        Array.Copy(originalMrg, 0, outBuf, 0, Math.Min(HeaderPreambleEnd, originalMrg.Length));

        int cursor = HeaderPreambleEnd;

        int Place(byte[] data)
        {
            int o = Align16(cursor);
            cursor = o + data.Length;
            if (cursor > blockSize) throw new InvalidOperationException("RH0 exceeds 1 MiB block");
            Array.Copy(data, 0, outBuf, o, data.Length);
            return o;
        }

        int nodeTreeOff = Place(nodeTree);
        int section1Off = Place(geo.Section1);
        int section2Off = Place(geo.Section2);
        int section1AltOff = geo.Section1Alt.Length > 0 ? Place(geo.Section1Alt) : section1Off;
        int section2AltOff = geo.Section2Alt.Length > 0 ? Place(geo.Section2Alt) : section2Off;
        int relocWalkOff = Place(geo.RelocWalk);

        // texTable is built after we know rh2/anm offsets, so reserve its size now
        byte[] texTable = BuildTexTablePlaceholder(texCount, dispatch.Count);
        int texTableOff = Place(texTable);

        int aux0Off = aux0.Length > 0 ? Place(aux0) : 0;
        int aux1Off = aux1.Length > 0 ? Place(aux1) : 0;
        int aux2Off = aux2.Length > 0 ? Place(aux2) : 0;

        var rh2Offs = new int[texCount];
        var anmOffs = new int[texCount];
        int texDataOff = 0;
        for (int i = 0; i < texCount; i++)
        {
            if (rh2[i].Length > 0)
            {
                rh2Offs[i] = Place(rh2[i]);
                if (texDataOff == 0) texDataOff = rh2Offs[i];
            }
        }
        for (int i = 0; i < texCount; i++)
            if (anm[i].Length > 0)
                anmOffs[i] = Place(anm[i]);

        // ---- header[0x0C] trailing-region chain ----
        // lSzModel_BindModelByAddr@0x1ee190 walks a cursor starting at header[0x0C], driven
        // by sectionFlags: bits 0-7 = embedded MOT blocks (advance by size@+4), bit 8/10 =
        // fixed-0x8000 regions, bit 9 and bits 11-18 = embedded RhText RH2 files (advance by
        // size@+8, RhText_BindAddress relocates them in place), bits 19/20 = align16(size@+8)
        // regions, bit 21 = final tail region (no size). Retail monsters carry flags
        // 0x80383875: MOTs + 3 effect textures + bit19/20/21 regions. We replace ONLY the MOT
        // part; everything else is captured verbatim and re-placed contiguously after our
        // MOTs. header[0x0C] must point at the chain even with zero motions, otherwise the
        // loader walks the RH0 header itself and RhText relocation corrupts the model.
        byte[] postMot = postMotEarly;
        int motOff;
        if (motBlocks.Length > 0)
        {
            motOff = Place(motBlocks);
            if (postMot.Length > 0) Place(postMot); // contiguous: cursor flows from MOTs into it
        }
        else
        {
            motOff = postMot.Length > 0 ? Place(postMot) : 0;
        }

        // ---- fill TexTable real pointers in place ----
        FillTexTable(outBuf, texTableOff, texCount, dispatch, rh2Offs, anmOffs);

        // ---- header fixups ----
        W32(outBuf, 0x04, ((uint)U32(originalMrg, 0x04) & 0xFFFFFF00u) | (uint)(motByte & 0xFF)); // keep upper flag bits
        W32(outBuf, 0x08, (uint)texDataOff);
        W32(outBuf, 0x0C, (uint)motOff);
        W32(outBuf, 0x10, (uint)nodeTreeOff);
        W32(outBuf, 0x14, (uint)nodeTree.Length);
        W32(outBuf, 0x18, (uint)section1Off);
        W32(outBuf, 0x1C, (uint)geo.Section1.Length);
        W32(outBuf, 0x20, (uint)section2Off);
        W32(outBuf, 0x24, (uint)geo.Section2.Length);
        W32(outBuf, 0x28, (uint)section1AltOff);
        W32(outBuf, 0x2C, (uint)geo.Section1Alt.Length);
        W32(outBuf, 0x30, (uint)section2AltOff);
        W32(outBuf, 0x34, (uint)geo.Section2Alt.Length);
        W32(outBuf, 0x38, (uint)texTableOff);
        W32(outBuf, 0x3C, (uint)texTable.Length);
        W32(outBuf, 0x40, (uint)aux0Off);
        W32(outBuf, 0x44, (uint)aux0.Length);
        W32(outBuf, 0x48, (uint)aux1Off);
        W32(outBuf, 0x4C, (uint)aux1.Length);
        W32(outBuf, 0x50, (uint)relocWalkOff);
        W32(outBuf, 0x54, (uint)geo.RelocWalk.Length);
        W32(outBuf, 0x58, (uint)aux2Off);
        W32(outBuf, 0x5C, (uint)aux2.Length);
        W32(outBuf, 0x60, 0);
        BinaryPrimitives.WriteSingleLittleEndian(outBuf.AsSpan(0x64), rebuilt.AnimTransScale);

        return outBuf;
    }

    // ---- TexTable -------------------------------------------------------------------
    /// Capture everything the header[0x0C] cursor chain covers AFTER the original MOT
    /// blocks (bits 8..21 regions), verbatim and contiguous, so it can be re-placed behind
    /// our regenerated MOTs. Returns empty if the original has no such regions.
    private static byte[] CapturePostMotChain(byte[] orig)
    {
        uint flags = U32(orig, 0x04);
        if ((flags & 0x003FFF00u) == 0) return Array.Empty<byte>();

        int cur = (int)U32(orig, 0x0C);
        for (int slot = 0; slot < 8; slot++) // skip original MOTs
            if ((flags & (1u << slot)) != 0)
                cur += (int)U32(orig, cur + 4);
        int start = cur;

        if ((flags & 0x100u) != 0) cur += 0x8000; // bit 8: fixed-size region
        if ((flags & 0x200u) != 0) cur += (int)U32(orig, cur + 8); // bit 9: RhText block
        if ((flags & 0x400u) != 0) cur += 0x8000; // bit 10: fixed-size region
        for (int i = 0; i < 8; i++) // bits 11-18: RhText blocks
            if ((flags & (1u << (11 + i))) != 0)
                cur += (int)U32(orig, cur + 8);
        if ((flags & 0x80000u) != 0) cur += ((int)U32(orig, cur + 8) + 0xF) & ~0xF; // bit 19
        if ((flags & 0x100000u) != 0) cur += ((int)U32(orig, cur + 8) + 0xF) & ~0xF; // bit 20
        if ((flags & 0x200000u) != 0)
        {
            // bit 21: final region with no stored size — capture to the end of meaningful
            // data in the block (trailing zeros trimmed, padded to 16).
            int end = orig.Length;
            while (end > cur && orig[end - 1] == 0) end--;
            cur = Math.Max(cur, (end + 0xF) & ~0xF);
        }
        cur = Math.Min(cur, orig.Length);
        if (cur <= start) return Array.Empty<byte>();
        var blob = new byte[cur - start];
        Array.Copy(orig, start, blob, 0, blob.Length);
        return blob;
    }

    // Layout: count, perTexOff, 0, 0 | TexBlock[count] (16B) | TexDispatchDesc[count] (8B) | dispatch entries (u32).
    private static byte[] BuildTexTablePlaceholder(int count, int dispatchCount)
    {
        int size = 0x10 + count * 16 + count * 8 + dispatchCount * 4;
        return new byte[Align16(size)];
    }

    private static void FillTexTable(byte[] buf, int ttOff, int count,
        IReadOnlyList<(int TexIdx, uint Entry)> texDispatch, int[] rh2Offs, int[] anmOffs)
    {
        int blocksOff = 0x10;
        int descOff = blocksOff + count * 16;
        int dispOff = descOff + count * 8;

        W32(buf, ttOff + 0x00, (uint)count);
        W32(buf, ttOff + 0x04, (uint)descOff); // perTexOff (rel TexTable)

        int disp = ttOff + dispOff; // absolute write cursor for dispatch entries
        for (int t = 0; t < count; t++)
        {
            // TexBlock
            int b = ttOff + blocksOff + t * 16;
            W32(buf, b + 0x00, (uint)(t < rh2Offs.Length ? rh2Offs[t] : 0)); // rh2Off (RH0-rel)
            W32(buf, b + 0x08, (uint)(t < anmOffs.Length ? anmOffs[t] : 0)); // postOff (RH0-rel)

            // Dispatch entries: lRhModel_SetupTexture@0x20fda0 copies 2 qwords (TEX0_1/TEX1_1
            // from this texture's RH2+0x30) to Section1copy + (entry & 0x0FFFFFFF) EVERY frame
            // (tag 0x2 = main copy, 0x4 = alt copy). The entries come from GeometryWriter: one
            // per texture-context record, pointing at its TEX0_1 placeholder (record + 0x70).
            // Emission order (main, then alt) is preserved.
            var entries = new List<uint>();
            foreach (var (texIdx, entry) in texDispatch)
                if (texIdx == t)
                    entries.Add(entry);
            int d = ttOff + descOff + t * 8;
            W32(buf, d + 0x00, (uint)entries.Count); // nDisp
            W32(buf, d + 0x04, (uint)(disp - ttOff)); // dispOff (rel TexTable)
            foreach (var e in entries)
            {
                W32(buf, disp, e);
                disp += 4;
            }
        }
    }

    // ---- helpers --------------------------------------------------------------------
    private static byte[] CopyRegion(byte[] src, int offField, int sizeField)
    {
        int off = (int)U32(src, offField), size = (int)U32(src, sizeField);
        if (off <= 0 || size <= 0 || off + size > src.Length) return Array.Empty<byte>();
        var b = new byte[size];
        Array.Copy(src, off, b, 0, size);
        return b;
    }

    // ---- texture encode strategy ----------------------------------------------------
    // Native (from-scratch POT RH2 via BuildNative) is used only when enabled AND the source
    // exceeds the donor's decoded dimensions; otherwise the validated donor template-patch
    // path (Encode) is kept. With no donor, native is the only way to produce a slot.
    private static byte[] EncodeTexture(ReadOnlySpan<byte> donor, byte[] rgba, int w, int h,
        bool allowNative, int maxDim, out bool wentNative)
    {
        wentNative = false;
        bool haveDonor = !donor.IsEmpty && donor.Length >= 0x60;
        if (haveDonor)
        {
            var (decW, decH) = DonorDecodedDims(donor);
            if (!allowNative || (w <= decW && h <= decH))
                return Rh2Encoder.Encode(donor, rgba, w, h);
        }
        else if (!allowNative)
        {
            return donor.ToArray(); // empty donor and native off: nothing to encode into
        }

        var (tw, th) = Rh2Encoder.ChooseTarget(w, h, maxDim);
        wentNative = true;
        return Rh2Encoder.BuildNative(rgba, w, h, tw, th);
    }

    // Decoded image dimensions a donor RH2 represents (PSMT4 decodes to half size).
    private static (int W, int H) DonorDecodedDims(ReadOnlySpan<byte> donor)
    {
        int psm = U16(donor, 0x50);
        int w = U16(donor, 0x54), h = U16(donor, 0x56);
        return psm == 0x14 ? (Math.Max(w / 2, 1), Math.Max(h / 2, 1)) : (w, h);
    }

    private static int Align16(int v) => (v + (Align - 1)) & ~(Align - 1);
    private static uint U32(ReadOnlySpan<byte> d, int o) => BinaryPrimitives.ReadUInt32LittleEndian(d.Slice(o));
    private static int U16(ReadOnlySpan<byte> d, int o) => BinaryPrimitives.ReadUInt16LittleEndian(d.Slice(o));
    private static void W32(byte[] d, int o, uint v) => BinaryPrimitives.WriteUInt32LittleEndian(d.AsSpan(o), v);
}