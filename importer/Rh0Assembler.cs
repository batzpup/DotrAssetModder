using System.Buffers.Binary;

namespace DotrAssetModder;

//Mostly AI

// === Step 6.6 — RH0 assembler ========================================================
// Combines the rebuilt sub-blocks into a single 1 MiB RH0 by TEMPLATE-INJECT: the
// original .mrg is the base, its header preamble (0x00..nodeTree) and aux2 are
// preserved VERBATIM, and only the blocks we regenerate are re-laid-out, with every
// header offset / size and TexTable pointer fixed up.
//
// Why template-inject rather than synthesis: the RH0 header carries a fixed preamble
// (incl. model-scale floats at +0xA8 and sectionFlags upper bits) whose exact engine
// use isn't fully reversed. RhModel_BindAddress consumes relocWalk + the four section
// bases (all regenerated correctly), and relocates each page terminator's term1
// (0x30000000|sec2Off) in place - exactly what GeometryWriter emits.
//
// aux0/aux1 are NOT copied: they are the per-frame lRhModel_DynamicAddressBind@0x20dd00
// fixup lists (offsets of every bone-bind d1 word + the opening-tag ADDR), tied to the
// Section1/Section1Alt layout, and are regenerated by GeometryWriter. Copying the
// originals verbatim leaves the new chain unbound -> VIF1 stall (black screen).
// aux2's consumer is unknown; it is zero-filled in retail and kept verbatim.
//
// Block order: header+preamble | nodeTree | section1 | section2 | section1Alt |
// section2Alt | relocWalk | texTable | aux0 | aux1 | aux2 | RH2[*] | ANM[*] | MOT | pad.
// =====================================================================================

public static class Rh0Assembler
{
    public const uint Rh0Magic = 0x00304852;
    private const int HeaderPreambleEnd = 0xB0; // header (0x68) + fixed preamble; nodeTree starts here in stock models
    private const int Align = 16;

    public sealed class TextureInput
    {
        public int TexIdx;
        public byte[]? Rgba; // edited texture (null => keep the original RH2 verbatim)
        public int Width, Height;

        // --- optional custom flipbook animation (see GlbImporter.TryParseAnimImageName /
        // ImportedModel.TextureAnimFrames for how these get populated from a glb) ---
        // When AnimFrameCount > 1, Rgba/Width/Height above hold the PACKED SPRITE-SHEET
        // (all frames laid out left-to-right, single row), and these fields describe how
        // to read it back as a flipbook, matching the real on-disk TexAnm entry format.
        // The 7 ANM modes confirmed via lSzModel_TexAnimConv string table (0x2cfa44):
        //   mode 0 = LOOP2, mode 1 = LOOP, mode 2 = REVERSE2, mode 3 = REVERSE,
        //   mode 4 = SHOT3, mode 5 = SHOT2, mode 6 = SHOT
        // All are flipbook cell-selection modes. There is NO scroll/UV-scroll mode.
        // flags=0x1B (previously misidentified as "scroll") is REVERSE mode (mode 3).
        // We synthesize LOOP mode (flags=0x8F, mode 1) matching the confirmed working
        // retail flipbook sample (electromagnetic_bagworm.mrg tex[1]).
        public int AnimFrameCount;       // 0 or 1 = static texture, no ANM entry written
        public int AnimBlockW, AnimBlockH;
        public int AnimTicksPerFrame = 5; // default matches the one real flipbook sample (aux0=aux1=5)
    }

    /// True when a valid RH0 magic sits at <paramref name="off"/> in <paramref name="src"/>.
    public static bool LooksLikeRh0(byte[] src, long off)
    {
        if (off < 0 || off + 4 > src.Length) return false;
        return U32(src, (int)off) == Rh0Magic;
    }

    /// Throws unless <paramref name="block"/> is exactly a fixed 1 MiB RH0 block (the
    /// monster-MRG slot shape) - used to validate a candidate template right before it's
    /// handed to Assemble, so a malformed selection fails with a clear message instead of
    /// a confusing downstream error.
    public static void ValidateRh0Block(byte[] block, string label)
    {
        if (block.Length != 0x100000 || !LooksLikeRh0(block, 0))
            throw new Exception(label + " is not a valid 1 MiB RH0 block");
    }

    /// Extracts a fixed 1 MiB RH0 block for monster-MRG-style import, from a user-selected
    /// "clean template" file that could be any of: a standalone 1 MiB RH0 block, a full
    /// data file using the indexed fixed-slot layout (block = modelIndex * 1 MiB), or a
    /// full data file where the caller already knows the model's current byte offset
    /// (currentBlockOff). Tries each interpretation in turn; throws if none match.
    public static byte[] ExtractTemplateBlock(byte[] src, int modelIndex, long currentBlockOff)
    {
        var block = new byte[0x100000];

        // A standalone RH0/MRG block.
        if (src.Length == 0x100000)
        {
            if (!LooksLikeRh0(src, 0))
                throw new Exception("selected template file is not an RH0 block");
            Array.Copy(src, 0, block, 0, 0x100000);
            return block;
        }

        // A full data file matching the current indexed archive layout.
        long byIndex = (long)modelIndex * 0x100000;
        if (byIndex >= 0 && byIndex + 0x100000 <= src.Length && LooksLikeRh0(src, byIndex))
        {
            Array.Copy(src, byIndex, block, 0, 0x100000);
            return block;
        }

        // A full data file matching the current byte offset within the selected data file.
        if (currentBlockOff >= 0 && currentBlockOff + 0x100000 <= src.Length && LooksLikeRh0(src, currentBlockOff))
        {
            Array.Copy(src, currentBlockOff, block, 0, 0x100000);
            return block;
        }

        throw new Exception("selected clean template does not contain an RH0 block at index 0 or the selected model index");
    }

    public static byte[] Assemble(byte[] originalMrg, RebuildPipeline.Result rebuilt,
        IReadOnlyList<TextureInput>? textures = null, int blockSize = 0x100000,
        bool rebuildNative = false, int maxTexDim = 512,
        bool neutralMissingTextures = true, bool preserveTemplateAnm = false,
        bool trimToContent = false)
    {
        if (U32(originalMrg, 0) != Rh0Magic) throw new InvalidOperationException("template is not an RH0");

        // ---- regenerate blocks ----
        byte[] nodeTree = NodeTreeWriter.Write(rebuilt.Nodes,
            (rebuilt.BoundsCenter.X, rebuilt.BoundsCenter.Y, rebuilt.BoundsCenter.Z), rebuilt.BoundsRadius);
        GeometryWriteResult geo = GeometryWriter.Write(rebuilt.Pages, rebuilt.MaxMeshSlot); // also fills EncPage.WalkOff
        var (motBlocks, motByte) = MotWriter.Write(rebuilt.Nodes.Count, rebuilt.Motions);

        // ---- textures: per TexTable entry, build RH2 + ANM ----
        // The TexTable count is NOT fixed to the template's: every texture-context record
        // GeometryWriter emitted MUST be reachable from a dispatch entry, because the
        // record's TEX0_1 placeholder is ZERO on disk and only becomes valid when
        // lRhModel_SetupTexture@0x20fda0 stamps it each frame. An unstamped record leaves
        // TEX0=0 (TBP0=0/PSMCT32) and the GS samples the live framebuffer at VRAM page 0 -
        // per-frame color flashing on the affected meshes. Both the per-frame stamper and
        // the load-time absolutiser (SzModel_BindTextureFile, called from
        // lSzModel_BindModelByAddr right after RhModel_BindAddress: absolutises rh2Off and
        // postOff, RhText_BindAddress per block, zeroes blk+0xC) read the count from
        // TexTable+0 and loop generically, and retail timeater ships 6 textures - so the
        // table may legitimately GROW beyond the template's count.
        //
        // Growth strategy: slots >= template count get an RH2 built from a DONOR template
        // block (slot i % origCount) - re-encoded with the glb-supplied image when one
        // exists, else the donor verbatim. If the grown layout would overflow the 1 MiB
        // block, extra slots are shed again and their dispatch entries are REMAPPED onto an
        // existing slot (wrong picture, but a stable one - never an unstamped record).
        // SzModel_BindTextureFile skips TexBlocks with rh2Off==0, which would make the
        // stamper read TEX0 from absolute address 0x30 - so a dispatched slot must always
        // end up with a non-empty RH2.
        int origTt = (int)U32(originalMrg, 0x38);
        int origCount = (int)U32(originalMrg, origTt);
        // The table is sized to EXACTLY the slots the new model dispatches to - it shrinks
        // as well as grows. A 6-texture template hosting a 4-texture model keeps 4 blocks:
        // the two surplus template RH2 payloads (and their ANM entries) are dropped, which
        // frees ~0x8530 each in the 1 MiB block. This is engine-safe because everything is
        // count-driven from TexTable+0: SzModel_BindTextureFile loops count when
        // absolutising, lRhModel_SetupTexture loops count when stamping, and the aux2
        // texture-animation remap values are bounds-checked against the same count before
        // use, so stale remap entries copied from the template simply never fire. Unused
        // slots BELOW the highest used index are positional and must stay - they keep the
        // template's RH2 verbatim.
        int texCount = 0;
        foreach (var (ti_, _) in geo.TexDispatch)
            if (ti_ + 1 > texCount)
                texCount = ti_ + 1;
        if (texCount == 0) texCount = Math.Min(origCount, 1); // degenerate: no textured pages

        var byTex = (textures ?? Array.Empty<TextureInput>()).Where(t => t != null)
            .GroupBy(t => t.TexIdx).ToDictionary(g => g.Key, g => g.First());

        // ---- UV-atlas composites for merged texture slots ----
        // RebuildPipeline.ApplyTexMerges retargeted excess slots' pages onto base slots
        // with V remapped into vertical bands; here the member images are stacked into one
        // canvas (band k of n, top to bottom — glTF v=0 is the top row) and re-encoded into
        // the base slot's template RH2. A member without a supplied image gets a neutral
        // grey band; if no member supplied an image the base keeps the template verbatim.
        foreach (var (baseSlot, members) in rebuilt.TexMerges)
        {
            int n = members.Count;
            if (n == 0) continue;
            var imgs = new TextureInput?[n];
            bool anyImg = false;
            for (int k = 0; k < n; k++)
                if (byTex.TryGetValue(members[k], out var t) && t.Rgba != null && t.Width > 0 && t.Height > 0)
                {
                    imgs[k] = t;
                    anyImg = true;
                }
            if (!anyImg) continue;

            int w = 0, bandH = 0;
            foreach (var t in imgs)
                if (t != null)
                {
                    w = Math.Max(w, t.Width);
                    bandH = Math.Max(bandH, t.Height);
                }
            var canvas = new byte[w * bandH * n * 4];
            for (int k = 0; k < n; k++)
            {
                var s = imgs[k];
                for (int y = 0; y < bandH; y++)
                {
                    int rowBase = ((k * bandH + y) * w) * 4;
                    for (int x = 0; x < w; x++)
                    {
                        int di = rowBase + x * 4;
                        if (s == null)
                        {
                            canvas[di] = canvas[di + 1] = canvas[di + 2] = 128;
                            canvas[di + 3] = 255;
                            continue;
                        }
                        int sx = w == s.Width ? x : x * s.Width / w;
                        int sy = bandH == s.Height ? y : y * s.Height / bandH;
                        int si = (sy * s.Width + sx) * 4;
                        canvas[di] = s.Rgba![si];
                        canvas[di + 1] = s.Rgba[si + 1];
                        canvas[di + 2] = s.Rgba[si + 2];
                        canvas[di + 3] = s.Rgba[si + 3];
                    }
                }
            }
            byTex[baseSlot] = new TextureInput { TexIdx = baseSlot, Rgba = canvas, Width = w, Height = bandH * n };
        }

        ReadOnlySpan<byte> OrigRh2(int slot)
        {
            if (slot < 0 || slot >= origCount) return ReadOnlySpan<byte>.Empty;
            int blk = origTt + 0x10 + slot * 16;
            int off = (int)U32(originalMrg, blk);
            if (off <= 0) return ReadOnlySpan<byte>.Empty;
            return originalMrg.AsSpan(off, (int)U32(originalMrg, off + 8));
        }

        var rh2 = new byte[texCount][];
        var anm = new byte[texCount][];
        var usedNative = new bool[texCount];
        for (int i = 0; i < texCount; i++)
        {
            // donor: the template's own slot for i < origCount, wrapped around for extras
            int donorSlot = origCount > 0 ? i % origCount : -1;
            var donor = OrigRh2(i < origCount ? i : donorSlot);
            if (donor.IsEmpty && origCount > 0) // wrap hit an empty slot
                for (int k = 0; k < origCount && donor.IsEmpty; k++)
                    donor = OrigRh2(k);

            if (byTex.TryGetValue(i, out var ti) && ti.Rgba != null && ti.Width > 0 && ti.Height > 0)
            {
                if (ti.AnimFrameCount > 1)
                {
                    // Sprite sheets must land at EXACTLY their own packed size (already
                    // POT/128/64-aligned, see GlbImporter's packer) - never run through the
                    // normal donor-fit/ChooseTarget path, which independently computes a
                    // POT target from the whole sheet's width and would stretch it,
                    // shifting every frame's cell boundary off-grid.
                    rh2[i] = Rh2Encoder.BuildNative(ti.Rgba, ti.Width, ti.Height, ti.Width, ti.Height);
                    usedNative[i] = true;
                }
                else
                {
                    // Normal single static texture - regular donor-fit/native encode path.
                    rh2[i] = EncodeTexture(donor, ti.Rgba, ti.Width, ti.Height, rebuildNative, maxTexDim, out usedNative[i]);
                }
            }
            else if (neutralMissingTextures)
            {
                // Do not inherit whatever picture happened to be in this slot from a previous import.
                // Encode a small neutral white texture into the donor RH2 container when possible, or
                // build a native RH2 from scratch if no donor texture exists.
                int nw = 128, nh = 128;
                if (!donor.IsEmpty && donor.Length >= 0x60)
                {
                    var dims = DonorDecodedDims(donor);
                    nw = Math.Clamp(dims.W, 1, Math.Max(1, maxTexDim));
                    nh = Math.Clamp(dims.H, 1, Math.Max(1, maxTexDim));
                }
                var neutral = CreateNeutralRgba(nw, nh);
                bool allowNativeFallback = donor.IsEmpty || rebuildNative;
                rh2[i] = EncodeTexture(donor, neutral, nw, nh, allowNativeFallback, maxTexDim, out usedNative[i]);
            }
            else
            {
                rh2[i] = donor.ToArray(); // explicit legacy mode: template texture verbatim
            }

            // Texture animation: a custom flipbook from the glb takes priority
            // and is synthesized fresh. Otherwise, template ANM is carried over only when
            // preserveTemplateAnm is set (default off for custom imports, to prevent
            // previous-slot ANM bleeding into an unrelated GLB).
            if (byTex.TryGetValue(i, out var anmTi) && anmTi.AnimFrameCount > 1)
            {
                anm[i] = BuildCustomTexAnimEntry(anmTi.AnimFrameCount, anmTi.AnimBlockW, anmTi.AnimBlockH,
                    anmTi.AnimTicksPerFrame);
            }
            else
            {
                int postOff = preserveTemplateAnm && i < origCount
                    ? (int)U32(originalMrg, origTt + 0x10 + i * 16 + 8)
                    : 0;
                anm[i] = postOff > 0 ? TexAnmWriter.ExtractEntries(originalMrg, postOff) : Array.Empty<byte>();
            }
        }

        // ---- aux lists ----
        // aux0/aux1 are LAYOUT-DEPENDENT: per-frame fixup lists for lRhModel_DynamicAddressBind
        // (offsets of every bone-bind d1 word + the opening-tag ADDR inside Section1/Section1Alt).
        // They are regenerated by GeometryWriter to match the new Section1 layout; copying the
        // originals verbatim leaves the DMA chain unbound -> VIF1 stall (black screen).
        // aux2's consumer is unknown; it is zero-filled in retail and kept verbatim.
        byte[] aux0 = geo.Aux0;
        byte[] aux1 = geo.Aux1;
        byte[] aux2 = CopyRegion(originalMrg, 0x58, 0x5C);
        // aux2 +0x00..0x7F = 32 option-object pointers to lists of Section1 offsets that
        // lRhModel_SetupOptionObject@0x20ffa0 stamps with NOP tags per frame — layout-
        // dependent, so zero them (optional geometry stays always visible). The rest of
        // aux2 (default mask, texture remap, anim-texture index) is layout-independent
        // config consumed by lRhModel_SetupTexture and is kept verbatim. Both sample
        // retail models ship with these pointers already zero.
        for (int i = 0; i < 0x80 && i < aux2.Length; i++) aux2[i] = 0;

        // ---- shed extra texture slots that would overflow the 1 MiB block ----
        byte[] postMotEarly = CapturePostMotChain(originalMrg);

        int EstimateTotal(int count)
        {
            int c = HeaderPreambleEnd;

            int Add(int len)
            {
                if (len > 0) c = ((c + 0xF) & ~0xF) + len;
                return c;
            }

            Add(nodeTree.Length);
            Add(geo.Section1.Length);
            Add(geo.Section2.Length);
            Add(geo.Section1Alt.Length);
            Add(geo.Section2Alt.Length);
            Add(geo.RelocWalk.Length);
            Add(Align16(0x10 + count * 16 + count * 8 + geo.TexDispatch.Count * 4)); // texTable
            Add(aux0.Length);
            Add(aux1.Length);
            Add(aux2.Length);
            for (int i = 0; i < count; i++) Add(rh2[i].Length);
            for (int i = 0; i < count; i++) Add(anm[i].Length);
            Add(motBlocks.Length);
            Add(postMotEarly.Length);
            return c;
        }

        // ---- native-rebuild budget: downgrade oversized native slots to fit the block ----
        // BuildNative slots can dwarf the donor's footprint. For the fixed 1 MiB monster.mrg
        // block, if the layout would overflow, downgrade native slots (largest first) back to
        // the donor-fit Encode/verbatim path until it fits. This keeps a valid render (lower
        // res) instead of throwing; the proper "grow the archive" handling is Phase 2/3.
        if (rebuildNative)
        {
            while (EstimateTotal(texCount) > blockSize)
            {
                int big = -1, bigLen = -1;
                for (int i = 0; i < texCount; i++)
                    if (usedNative[i] && rh2[i].Length > bigLen)
                    {
                        bigLen = rh2[i].Length;
                        big = i;
                    }
                if (big < 0) break; // nothing native left to downgrade

                int dSlot = big < origCount ? big : (origCount > 0 ? big % origCount : -1);
                var donor = OrigRh2(dSlot);
                if (donor.IsEmpty && origCount > 0)
                    for (int k = 0; k < origCount && donor.IsEmpty; k++)
                        donor = OrigRh2(k);
                rh2[big] = (byTex.TryGetValue(big, out var t) && t.Rgba != null && !donor.IsEmpty)
                    ? Rh2Encoder.Encode(donor, t.Rgba, t.Width, t.Height)
                    : donor.ToArray();
                usedNative[big] = false;
            }
        }

        while (texCount > origCount && EstimateTotal(texCount) > blockSize) texCount--;
        if (texCount != rh2.Length)
        {
            Array.Resize(ref rh2, texCount);
            Array.Resize(ref anm, texCount);
        }

        // ---- dispatch remap: every entry must land on a slot with a real RH2 ----
        int fallbackSlot = -1;
        for (int i = 0; i < texCount; i++)
            if (rh2[i].Length > 0)
            {
                fallbackSlot = i;
                break;
            }
        var dispatch = new List<(int TexIdx, uint Entry)>(geo.TexDispatch.Count);
        foreach (var (ti_, entry) in geo.TexDispatch)
        {
            int t = ti_;
            if (t >= texCount || rh2[t].Length == 0)
            {
                int wrapped = texCount > 0 ? t % texCount : -1;
                t = (wrapped >= 0 && rh2[wrapped].Length > 0) ? wrapped : fallbackSlot;
            }
            if (t < 0)
                throw new InvalidOperationException(
                    "the template model carries no RH2 texture payloads, so there is no donor " +
                    "block to encode the import's textures into (RH2 synthesis from scratch is " +
                    "not supported) - inject over a template that has at least one texture");
            dispatch.Add((t, entry));
        }

        // ---- assign offsets (16-aligned), header+preamble copied first ----
        var outBuf = new byte[blockSize];
        Array.Copy(originalMrg, 0, outBuf, 0, Math.Min(HeaderPreambleEnd, originalMrg.Length));

        int cursor = HeaderPreambleEnd;

        int Place(byte[] data)
        {
            int o = Align16(cursor);
            cursor = o + data.Length;
            if (cursor > blockSize) throw new InvalidOperationException("RH0 exceeds 1 MiB block");
            Array.Copy(data, 0, outBuf, o, data.Length);
            return o;
        }

        int nodeTreeOff = Place(nodeTree);
        int section1Off = Place(geo.Section1);
        int section2Off = Place(geo.Section2);
        int section1AltOff = geo.Section1Alt.Length > 0 ? Place(geo.Section1Alt) : section1Off;
        int section2AltOff = geo.Section2Alt.Length > 0 ? Place(geo.Section2Alt) : section2Off;
        int relocWalkOff = Place(geo.RelocWalk);

        // texTable is built after we know rh2/anm offsets, so reserve its size now
        byte[] texTable = BuildTexTablePlaceholder(texCount, dispatch.Count);
        int texTableOff = Place(texTable);

        int aux0Off = aux0.Length > 0 ? Place(aux0) : 0;
        int aux1Off = aux1.Length > 0 ? Place(aux1) : 0;
        int aux2Off = aux2.Length > 0 ? Place(aux2) : 0;

        var rh2Offs = new int[texCount];
        var anmOffs = new int[texCount];
        int texDataOff = 0;
        for (int i = 0; i < texCount; i++)
        {
            if (rh2[i].Length > 0)
            {
                rh2Offs[i] = Place(rh2[i]);
                if (texDataOff == 0) texDataOff = rh2Offs[i];
            }
        }
        for (int i = 0; i < texCount; i++)
            if (anm[i].Length > 0)
                anmOffs[i] = Place(anm[i]);

        // ---- header[0x0C] trailing-region chain ----
        // lSzModel_BindModelByAddr@0x1ee190 walks a cursor starting at header[0x0C], driven
        // by sectionFlags: bits 0-7 = embedded MOT blocks (advance by size@+4), bit 8/10 =
        // fixed-0x8000 regions, bit 9 and bits 11-18 = embedded RhText RH2 files (advance by
        // size@+8, RhText_BindAddress relocates them in place), bits 19/20 = align16(size@+8)
        // regions, bit 21 = final tail region (no size). Retail monsters carry flags
        // 0x80383875: MOTs + 3 effect textures + bit19/20/21 regions. We replace ONLY the MOT
        // part; everything else is captured verbatim and re-placed contiguously after our
        // MOTs. header[0x0C] must point at the chain even with zero motions, otherwise the
        // loader walks the RH0 header itself and RhText relocation corrupts the model.
        //
        // BUG FIX: when there are neither MOT blocks nor any post-mot chain content, this
        // used to write a literal 0 here. 0 is not "no chain" to any consumer - both the
        // engine's walker (cur = blockBase + header[0x0C]) and this codebase's own
        // ComputeBlockEnd use the SAME formula unconditionally, so header[0x0C]=0 makes the
        // block's computed end equal its own start (a phantom zero-length block). With no
        // chain content, header[0x0C] must instead hold the cursor's current value - the
        // real, already-placed end of the block (node tree + geometry + textures) - exactly
        // like the motBlocks.Length>0 branch's `motOff = Place(motBlocks)` does for a
        // non-empty chain. This was corrupting ModelPackIndex.Scan (and the engine itself)
        // for every assembled model with zero embedded motion and zero trailing chain data,
        // i.e. most freshly-imported custom GLBs.
        byte[] postMot = postMotEarly;
        int motOff;
        if (motBlocks.Length > 0)
        {
            motOff = Place(motBlocks);
            if (postMot.Length > 0) Place(postMot); // contiguous: cursor flows from MOTs into it
        }
        else if (postMot.Length > 0)
        {
            motOff = Place(postMot);
        }
        else
        {
            motOff = cursor; // no chain at all: point at the real end of content, not 0
        }

        // ---- fill TexTable real pointers in place ----
        FillTexTable(outBuf, texTableOff, texCount, dispatch, rh2Offs, anmOffs);

        // ---- header fixups ----
        W32(outBuf, 0x04, ((uint)U32(originalMrg, 0x04) & 0xFFFFFF00u) | (uint)(motByte & 0xFF)); // keep upper flag bits
        W32(outBuf, 0x08, (uint)texDataOff);
        W32(outBuf, 0x0C, (uint)motOff);
        W32(outBuf, 0x10, (uint)nodeTreeOff);
        W32(outBuf, 0x14, (uint)nodeTree.Length);
        W32(outBuf, 0x18, (uint)section1Off);
        W32(outBuf, 0x1C, (uint)geo.Section1.Length);
        W32(outBuf, 0x20, (uint)section2Off);
        W32(outBuf, 0x24, (uint)geo.Section2.Length);
        W32(outBuf, 0x28, (uint)section1AltOff);
        W32(outBuf, 0x2C, (uint)geo.Section1Alt.Length);
        W32(outBuf, 0x30, (uint)section2AltOff);
        W32(outBuf, 0x34, (uint)geo.Section2Alt.Length);
        W32(outBuf, 0x38, (uint)texTableOff);
        W32(outBuf, 0x3C, (uint)texTable.Length);
        W32(outBuf, 0x40, (uint)aux0Off);
        W32(outBuf, 0x44, (uint)aux0.Length);
        W32(outBuf, 0x48, (uint)aux1Off);
        W32(outBuf, 0x4C, (uint)aux1.Length);
        W32(outBuf, 0x50, (uint)relocWalkOff);
        W32(outBuf, 0x54, (uint)geo.RelocWalk.Length);
        W32(outBuf, 0x58, (uint)aux2Off);
        W32(outBuf, 0x5C, (uint)aux2.Length);
        W32(outBuf, 0x60, 0);
        BinaryPrimitives.WriteSingleLittleEndian(outBuf.AsSpan(0x64), rebuilt.AnimTransScale);

        // ---- Fix 2: validate the header[0x0C] region chain is reachable ----
        // OverlayB (sectionFlags bit 0x400) and the effect/camera-motion regions are bound by
        // lSzModel_BindModelByAddr@0x1f0500 walking the chain rooted at header[0x0C]. If MOT
        // replacement shifted the chain so a region stop lands on the wrong offset, OverlayB
        // points at garbage and SzModel_BattleSeq spawns its particle effect at world origin.
        // Re-walk the just-written block with the same logic the engine uses and fail the
        // build (with a precise message) instead of shipping a model that spawns at (0,0,0).
        ValidateRegionChain(outBuf, cursor, motByte);

        if (trimToContent)
        {
            // cursor holds the true end of all placed content (every Place() call advances
            // it by exactly what it wrote, 16-aligned) - for a MODEL.MRG-style variable
            // pack there is no fixed slot size to pad out to, so return only the
            // meaningful bytes. blockSize above still acts as a sane upper-bound safety
            // ceiling (Place() throws if content would exceed it), it just no longer
            // dictates the returned array's length.
            var trimmed = new byte[cursor];
            Array.Copy(outBuf, 0, trimmed, 0, cursor);
            return trimmed;
        }
        return outBuf;
    }

    // ---- TexTable -------------------------------------------------------------------
    /// Capture everything the header[0x0C] cursor chain covers AFTER the original MOT
    /// blocks (bits 8..21 regions), verbatim and contiguous, so it can be re-placed behind
    /// our regenerated MOTs. Returns empty if the original has no such regions.
    /// Computes the true end (one-past-last-byte) of the RH0 block starting at
    /// <paramref name="blockBase"/> within <paramref name="data"/>, by walking the exact
    /// same header[0x0C]-rooted chain CapturePostMotChain decodes for in-place rebuilds.
    /// Shared so the MODEL.MRG pack indexer (ModelPackIndex.cs) and the single-block
    /// extractor agree on block boundaries by construction, rather than via two
    /// independently-maintained copies of this logic. <paramref name="postMotStart"/>
    /// receives the offset where the post-mot-chain regions begin (right after the
    /// original embedded MOTs, bits 0-7) - this is CapturePostMotChain's capture start.
    /// Returns -1 if this doesn't look like a valid RH0 header (caller should treat the
    /// candidate position as a false-positive magic match, not a real block).
    internal static long ComputeBlockEnd(ReadOnlySpan<byte> data, long blockBase, out long postMotStart)
    {
        postMotStart = -1;
        if (blockBase < 0 || blockBase + 0x10 > data.Length) return -1;
        if (U32(data, (int)blockBase) != Rh0Magic) return -1;

        uint flags = U32(data, (int)blockBase + 0x04);
        long cur = blockBase + U32(data, (int)blockBase + 0x0C);
        if (cur < blockBase || cur > data.Length) return -1;

        for (int slot = 0; slot < 8; slot++) // bits 0-7: embedded MOT blocks
            if ((flags & (1u << slot)) != 0)
            {
                if (cur + 8 > data.Length) return -1;
                cur += U32(data, (int)cur + 4);
            }
        postMotStart = cur;
        if ((flags & 0x100u) != 0) cur += 0x8000; // bit 8: fixed-size region
        if ((flags & 0x200u) != 0) { if (cur + 12 > data.Length) return -1; cur += U32(data, (int)cur + 8); } // bit 9: RhText
        if ((flags & 0x400u) != 0) cur += 0x8000; // bit 10: fixed-size region
        for (int i = 0; i < 8; i++) // bits 11-18: RhText blocks
            if ((flags & (1u << (11 + i))) != 0)
            {
                if (cur + 12 > data.Length) return -1;
                cur += U32(data, (int)cur + 8);
            }
        if ((flags & 0x80000u) != 0) { if (cur + 12 > data.Length) return -1; cur += (U32(data, (int)cur + 8) + 0xF) & ~0xFu; } // bit 19
        if ((flags & 0x100000u) != 0) { if (cur + 12 > data.Length) return -1; cur += (U32(data, (int)cur + 8) + 0xF) & ~0xFu; } // bit 20
        if ((flags & 0x200000u) != 0)
        {
            // bit 21: final region with no stored size - needs the caller's true container
            // end to trim trailing zeros against (CapturePostMotChain has it via
            // orig.Length; pack scanning does not, and this bit hasn't been observed in
            // MODEL.MRG). Signal "open-ended" by returning postMotStart unmodified plus a
            // sentinel the pack scanner treats as "cannot determine, stop scanning".
            return long.MaxValue;
        }
        return Math.Min(cur, data.Length);
    }

    /// Fix 2 — post-assembly sanity check on the header[0x0C] trailing-region chain.
    /// Walks the freshly-written block the same way the engine's binder does
    /// (lSzModel_BindModelByAddr@0x1f0500 / ComputeBlockEnd) and throws if anything the
    /// loader would dereference is out of range. <paramref name="contentEnd"/> is the
    /// assembler's cursor (true one-past-last placed byte); <paramref name="motByte"/> is the
    /// sectionFlags low byte we wrote (bits 0-7 = embedded MOT slots).
    ///
    /// Checks, in order:
    ///   * header[0x0C] (chain root) sits inside placed content,
    ///   * each embedded MOT slot bit set in bits 0-7 has a real MOT magic at the walked
    ///     position (catches a sectionFlags byte that desynced from the emitted MOT blocks),
    ///   * the full walk via ComputeBlockEnd succeeds (return != -1: no region size ran off
    ///     the end), and the computed end does not exceed the block.
    /// A bit-21 open-ended tail (ComputeBlockEnd returns long.MaxValue) is accepted: it is
    /// trimmed against the block length exactly as CapturePostMotChain does, so it cannot
    /// over-run.
    private static void ValidateRegionChain(byte[] block, int contentEnd, int motByte)
    {
        uint flags = U32(block, 0x04);
        long chainRoot = U32(block, 0x0C);

        if (chainRoot < HeaderPreambleEnd || chainRoot > contentEnd)
            throw new InvalidOperationException(
                $"RH0 region chain root (header[0x0C]={chainRoot:X}) is outside placed content " +
                $"(0x{HeaderPreambleEnd:X}..0x{contentEnd:X}); OverlayB/effect binding would " +
                "dereference garbage and spawn battle effects at world origin.");

        // Walk the embedded MOT slots (bits 0-7) and confirm each declared slot really has a
        // MOT block where the loader will look. motByte and the emitted blocks must agree.
        long cur = chainRoot;
        for (int slot = 0; slot < 8; slot++)
        {
            if ((flags & (1u << slot)) == 0) continue;
            if (cur + 8 > block.Length)
                throw new InvalidOperationException(
                    $"RH0 MOT slot {slot} chain entry runs past the block end (cur=0x{cur:X}).");
            if (U32(block, (int)cur) != MotWriter.Magic)
                throw new InvalidOperationException(
                    $"RH0 sectionFlags bit {slot} is set but no MOT magic is present at the " +
                    $"chain position 0x{cur:X}. The sectionFlags low byte (0x{motByte & 0xFF:X2}) " +
                    "is out of sync with the emitted MOT blocks; SzModel_SetAnimIntr would " +
                    "null-fault and stall the 3D battle.");
            cur += U32(block, (int)cur + 4);
        }

        // Full chain walk (MOTs + bits 8..21 regions) via the shared engine-equivalent logic.
        long end = ComputeBlockEnd(block, 0, out long postMotStart);
        if (end == -1)
            throw new InvalidOperationException(
                "RH0 region chain walk failed: a region size field points past the block end. " +
                "The header[0x0C] chain is malformed and the engine's binder would read out of " +
                "bounds (black screen / corrupt effects).");
        if (postMotStart < 0 || postMotStart > block.Length)
            throw new InvalidOperationException(
                $"RH0 post-MOT chain start (0x{postMotStart:X}) is out of range.");
        if (end != long.MaxValue && end > block.Length)
            throw new InvalidOperationException(
                $"RH0 region chain computed end (0x{end:X}) exceeds the block size " +
                $"(0x{block.Length:X}).");
    }

    private static byte[] CapturePostMotChain(byte[] orig)
    {
        uint flags = U32(orig, 0x04);
        if ((flags & 0x003FFF00u) == 0) return Array.Empty<byte>();

        long end = ComputeBlockEnd(orig, 0, out long start);
        if (end == long.MaxValue)
        {
            // bit 21 (open-ended trailing region): trim trailing zeros against this
            // single block's own true length, exactly as the original implementation did.
            int e = orig.Length;
            while (e > start && orig[e - 1] == 0) e--;
            end = Math.Max(start, (e + 0xF) & ~0xF);
        }
        end = Math.Min(end, orig.Length);
        if (end <= start) return Array.Empty<byte>();
        var blob = new byte[end - start];
        Array.Copy(orig, start, blob, 0, blob.Length);
        return blob;
    }

    // Layout: count, perTexOff, 0, 0 | TexBlock[count] (16B) | TexDispatchDesc[count] (8B) | dispatch entries (u32).
    private static byte[] BuildTexTablePlaceholder(int count, int dispatchCount)
    {
        int size = 0x10 + count * 16 + count * 8 + dispatchCount * 4;
        return new byte[Align16(size)];
    }

    private static void FillTexTable(byte[] buf, int ttOff, int count,
        IReadOnlyList<(int TexIdx, uint Entry)> texDispatch, int[] rh2Offs, int[] anmOffs)
    {
        int blocksOff = 0x10;
        int descOff = blocksOff + count * 16;
        int dispOff = descOff + count * 8;

        W32(buf, ttOff + 0x00, (uint)count);
        W32(buf, ttOff + 0x04, (uint)descOff); // perTexOff (rel TexTable)

        int disp = ttOff + dispOff; // absolute write cursor for dispatch entries
        for (int t = 0; t < count; t++)
        {
            // TexBlock
            int b = ttOff + blocksOff + t * 16;
            W32(buf, b + 0x00, (uint)(t < rh2Offs.Length ? rh2Offs[t] : 0)); // rh2Off (RH0-rel)
            W32(buf, b + 0x08, (uint)(t < anmOffs.Length ? anmOffs[t] : 0)); // postOff (RH0-rel)

            // Dispatch entries: lRhModel_SetupTexture@0x20fda0 copies 2 qwords (TEX0_1/TEX1_1
            // from this texture's RH2+0x30) to Section1copy + (entry & 0x0FFFFFFF) EVERY frame
            // (tag 0x2 = main copy, 0x4 = alt copy). The entries come from GeometryWriter: one
            // per texture-context record, pointing at its TEX0_1 placeholder (record + 0x70).
            // Emission order (main, then alt) is preserved.
            var entries = new List<uint>();
            foreach (var (texIdx, entry) in texDispatch)
                if (texIdx == t)
                    entries.Add(entry);
            int d = ttOff + descOff + t * 8;
            W32(buf, d + 0x00, (uint)entries.Count); // nDisp
            W32(buf, d + 0x04, (uint)(disp - ttOff)); // dispOff (rel TexTable)
            foreach (var e in entries)
            {
                W32(buf, disp, e);
                disp += 4;
            }
        }
    }

    // ---- helpers --------------------------------------------------------------------
    private static byte[] CopyRegion(byte[] src, int offField, int sizeField)
    {
        int off = (int)U32(src, offField), size = (int)U32(src, sizeField);
        if (off <= 0 || size <= 0 || off + size > src.Length) return Array.Empty<byte>();
        var b = new byte[size];
        Array.Copy(src, off, b, 0, size);
        return b;
    }

    // ---- texture encode strategy ----------------------------------------------------
    // Native (from-scratch POT RH2 via BuildNative) is used only when enabled AND the source
    // exceeds the donor's decoded dimensions; otherwise the validated donor template-patch
    // path (Encode) is kept. With no donor, native is the only way to produce a slot.
    private static byte[] CreateNeutralRgba(int w, int h)
    {
        w = Math.Max(1, w);
        h = Math.Max(1, h);
        var rgba = new byte[w * h * 4];
        for (int i = 0; i < rgba.Length; i += 4)
        {
            rgba[i + 0] = 255;
            rgba[i + 1] = 255;
            rgba[i + 2] = 255;
            rgba[i + 3] = 255;
        }
        return rgba;
    }

    // Real on-disk TexAnm entry format (24 bytes), confirmed by reading a genuine retail
    // flipbook entry (electromagnetic_bagworm.mrg tex slot 1) AND by disassembling its
    // runtime consumer, SzModel_LoadTexAnim_Pipe@0x1e80a0 (called every frame from
    // SzModel_LoadTexture_Pipe, gated on TexBlock.postOff != 0): flags=0x8F (bit0=last=1;
    // bits 3-5 select one of 7 sub-mode handlers via a jump table at 0x2cb440 - mode 0,
    // the flipbook case here, is reached when src==dst on both axes, confirmed by the
    // disassembly explicitly comparing srcX/dstX and srcY/dstY and short-circuiting to
    // the simple path when equal), slotMask=0xFF (bitmask of which SzModel_GetAnim()
    // states this entry is active for), grid=0x42 (LOW nibble=cols=2, HIGH nibble=
    // rows=4 - confirmed via the disassembly's `grid & 0xF` for cols and `grid >> 4` for
    // rows; I originally had this backwards), aux0=aux1=5 (tick hold time), blockW=64
    // blockH=16 (one cell's size - the STORED RH2 TEXTURE for this retail sample is only
    // 128x64 total, i.e. cols*blockW=2*64=128, rows*blockH=4*16=64 - frames are small
    // grid cells cut from one modest texture, NOT full-resolution copies of a large
    // source image laid out in a strip). The engine genuinely animates this per frame:
    // `+0x14` (counter) increments every tick via SzModel_LoadTexAnim_Pipe, and the cell
    // offset is computed live from it (confirmed in the disassembly: a real division/
    // modulo against cols, not a precomputed constant) - this is not a one-shot blit.
    //
    // This builds a SINGLE-ROW flipbook (rows=1, cols=frameCount) for any custom imported
    // animation - a strict subset of what the format supports (multi-row grids exist too,
    // per the real sample above) but simpler to pack and fully sufficient for any frame
    // count, since a sprite sheet doesn't need to be square. Per-cell size should stay
    // small and close to retail's own scale (tens of pixels, not hundreds+) - see
    // GlbImporter.DecodeGlbTextures' maxDim handling for animated slots.
    private static byte[] BuildCustomTexAnimEntry(int frameCount, int blockW, int blockH, int ticksPerFrame)
    {
        const int EntrySize = 0x18;
        frameCount = Math.Clamp(frameCount, 1, 15); // grid nibble is 4 bits; 15 is the real ceiling
        var e = new byte[EntrySize];
        e[0] = 0x8F;          // flags: bit0=last(1) + the other bits a confirmed-working real entry carried
        e[1] = 0xFF;          // slotMask: matches every real sample seen so far
        e[2] = (byte)(0x10 | (frameCount & 0xF)); // grid: low nibble=cols, high nibble=rows. NOTE: the
                              // only real retail sample decoded used cols=2,rows=4 (0x42) - a single-
                              // row cols=N,rows=1 layout (this line) has NEVER been confirmed against
                              // real working data and may hit a code path retail never exercises.
        e[3] = 1;             // state: the real retail sample has this =1, not 0 - corrected after
                              // confirming via disassembly that SzModel_LoadTexAnim_Pipe never actually
                              // reads offset +3 at all, so this field's true role is still unconfirmed,
                              // but copying the one known-working value is safer than an unverified 0.
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(4), (ushort)Math.Clamp(ticksPerFrame, 1, ushort.MaxValue));  // aux0
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(6), (ushort)Math.Clamp(ticksPerFrame, 1, ushort.MaxValue));  // aux1 (mirrors aux0)
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(8), (ushort)Math.Clamp(blockW, 1, ushort.MaxValue));
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(0xA), (ushort)Math.Clamp(blockH, 1, ushort.MaxValue));
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(0xC), 0);  // srcX
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(0xE), 0);  // srcY
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(0x10), 0); // dstX
        BinaryPrimitives.WriteUInt16LittleEndian(e.AsSpan(0x12), 0); // dstY
        // +0x14 counter: runtime, already 0 from `new byte[]`
        return e;
    }

    private static byte[] EncodeTexture(ReadOnlySpan<byte> donor, byte[] rgba, int w, int h,
        bool allowNative, int maxDim, out bool wentNative)
    {
        wentNative = false;
        bool haveDonor = !donor.IsEmpty && donor.Length >= 0x60;
        if (haveDonor)
        {
            var (decW, decH) = DonorDecodedDims(donor);
            if (!allowNative || (w <= decW && h <= decH))
                return Rh2Encoder.Encode(donor, rgba, w, h);
        }
        else if (!allowNative)
        {
            return donor.ToArray(); // empty donor and native off: nothing to encode into
        }

        var (tw, th) = Rh2Encoder.ChooseTarget(w, h, maxDim);
        wentNative = true;
        return Rh2Encoder.BuildNative(rgba, w, h, tw, th);
    }

    // Decoded image dimensions a donor RH2 represents (PSMT4 decodes to half size).
    private static (int W, int H) DonorDecodedDims(ReadOnlySpan<byte> donor)
    {
        int psm = U16(donor, 0x50);
        int w = U16(donor, 0x54), h = U16(donor, 0x56);
        return psm == 0x14 ? (Math.Max(w / 2, 1), Math.Max(h / 2, 1)) : (w, h);
    }

    private static int Align16(int v) => (v + (Align - 1)) & ~(Align - 1);
    private static uint U32(ReadOnlySpan<byte> d, int o) => BinaryPrimitives.ReadUInt32LittleEndian(d.Slice(o));
    private static int U16(ReadOnlySpan<byte> d, int o) => BinaryPrimitives.ReadUInt16LittleEndian(d.Slice(o));
    private static void W32(byte[] d, int o, uint v) => BinaryPrimitives.WriteUInt32LittleEndian(d.AsSpan(o), v);
